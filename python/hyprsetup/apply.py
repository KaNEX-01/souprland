"""Applies settings to the running session — without installing packages or sudo.

This module is the engine of the settings app (hyprsetup). The same job used
to be done by calling ``install.sh --configs-only``; that path was dropped
for three reasons:

1. Calling the installer meant running the whole install flow (preflight,
   component selection, hooks) just to change a setting. Since
   ``run_hooks_step`` was not guarded by ``SKIP_PACKAGES``, with a plugin
   selected **every settings change** could trigger ``hyprpm add``/``enable``
   — i.e. a build from source (see modules/hypr.sh:_hyprpm_enable).
2. Every apply started a ``bash`` + ``python3`` process; far too heavy for
   instant (debounced) applying.
3. ``render_install`` copied EVERY file it generated. Moving one slider
   rewrote 84 files, and so produced a reason to restart every unrelated
   daemon.

The flow here solves all three:

    collect variables → render (~8 ms) → write ONLY files whose content differs
    → restart ONLY the daemons owning the written files

No code path needs root; no packages are installed.
"""

