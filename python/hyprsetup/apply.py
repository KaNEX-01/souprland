#: Ownership marker put into the monitor/workspace files we generate
#: (templates/hypr/monitors.conf.tmpl and modules/hypr.sh's placeholder).
#: If the marker is present the file is ours; when nwg-displays rewrites the
#: file the marker disappears too, so ownership changes hands by itself.
OWNER_MARK = "hyprsetup:managed"

#: "# Generated by nwg-displays on 2026-09-23 at 10:50:44. Do not edit
#: manually." — nwg-displays (and similar tools) write this line at the top of
#: the file they generate.
_FOREIGN_RE = re.compile(r"generated by\s+([A-Za-z0-9][A-Za-z0-9._+-]*)",
                         re.IGNORECASE)

#: Targets whose ownership is RESPECTED (relative to ~/.config). Only these
#: four files are protected; a rule applied to "every file" would silently
#: freeze the config because of other tools (like waypaper) that later touch
#: a file they themselves generated.
#:
#: Reason: when someone who set up their monitor layout with nwg-displays
#: changed ANY setting from the script, MANAGE_MONITORS=1 (the default)
#: rewrote monitors.conf with placeholder content and the layout was reset.
PROTECTED_TARGETS: tuple[str, ...] = (
    "hypr/monitors.conf", "hypr/workspaces.conf",
    "hypr/hyprland/monitors.lua", "hypr/hyprland/workspaces.lua",
)


#: Targets KDE reads and writes via KConfig. KDE apps (Dolphin, kded6, the
#: file dialog) rewrite these files in their own format: they drop comments,
#: sort keys and add their own state keys. A byte comparison therefore said
#: "changed" on EVERY apply and rewrote the file; these are compared by
#: meaning instead (_kconfig_covers).
KCONFIG_TARGETS: frozenset[str] = frozenset({"dolphinrc", "kdeglobals"})


def _kconfig_entries(text: str) -> dict[tuple[str, str], str]:
    """KConfig file → {(group, key): value}; comments and blank lines are skipped."""
    entries: dict[tuple[str, str], str] = {}
    group = ""
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", ";")):
            continue
        if line.startswith("["):
            group = line
            continue
        key, sep, value = line.partition("=")
        if sep:
            entries[(group, key.strip())] = value.strip()
    return entries


def _kconfig_covers(current: bytes, new: bytes) -> bool:
    """Does the file on disk contain every key we would write, with the same value?

    Keys the app added itself (window size etc.) do not count as a difference;
    rewriting would delete them.
    """
    have = _kconfig_entries(current.decode("utf-8", errors="replace"))
    want = _kconfig_entries(new.decode("utf-8", errors="replace"))
    return all(have.get(item) == value for item, value in want.items())


def foreign_owner(path: Path) -> str | None:
    """The other tool's name if ANOTHER tool generated the file, else ``None``.

    Applies the same rule as ``lib/core.sh:foreign_config_owner``; if one
    changes the other must too (tools/test.sh compares them).
    """
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:4096]
    except OSError:
        return None
    if OWNER_MARK in head:
        return None
    match = _FOREIGN_RE.search(head)
    if match is None:
        return None
    name = match.group(1)
    return None if name.lower().startswith("hyprsetup") else name


#: Time waited after killing and restarting a daemon. Taken verbatim from
#: install.sh's restart_daemons_step: without the wait the new process starts
#: before the old one has released its socket, and silently dies.
_RESTART_SETTLE = 0.3


# ----------------------------------------------------------------- results ---
@dataclass
class ApplyResult:
    """Result of a single apply round."""

    #: Paths relative to ~/.config — only the ones that REALLY changed.
    written: list[str] = field(default_factory=list)
    #: Human-readable names of the actions run (shown in the UI).
    actions: list[str] = field(default_factory=list)
    #: Component ids skipped because their package is not installed.
    skipped: list[str] = field(default_factory=list)
    #: Non-fatal errors; the UI shows them as warnings.
    errors: list[str] = field(default_factory=list)
    #: Files NOT OVERWRITTEN because another tool generated them
    #: {relative path: tool name} — see PROTECTED_TARGETS.
    protected: dict[str, str] = field(default_factory=dict)

    @property
    def changed(self) -> bool:
        return bool(self.written)


