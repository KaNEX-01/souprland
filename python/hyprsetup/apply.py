def action_for(rel_path: str) -> str | None:
    """Action name for a relative config path.

    ``""`` = "writing is enough, nothing to do" (a deliberate decision).
    ``None`` = matches no rule (unmapped target — the test catches this).
    """
    path = rel_path.replace(os.sep, "/")
    for prefix, action in _ACTION_RULES:
        if prefix.endswith("/"):
            if path.startswith(prefix):
                return action
        elif path == prefix:
            return action
    return None


# ------------------------------------------------------------------ applier ---
class Applier:
    """Engine that renders the settings, writes them to disk and applies them to the session.

    A single instance is long-lived: it remembers the installed package set
    and the last applied primary tools (bar/notifications/wallpaper) — when
    the backend changes the OLD backend must be shut down too, and only
    "what was the previous value" tells us that.
    """

    def __init__(self, root: Path, catalog: Catalog,
                 keybinds: keybinds_mod.Keybinds | None = None,
                 config_home: Path | None = None,
                 dry_run: bool = False) -> None:
        self.root = Path(root)
        self.templates = self.root / "templates"
        self.catalog = catalog
        self.keybinds = keybinds
        self.config_home = Path(
            config_home or os.environ.get("XDG_CONFIG_HOME")
            or Path.home() / ".config")
        #: Root for steps writing OUTSIDE ~/.config (wallpaper, Firefox
        #: profile). When config_home is given its parent is used, so tests can
        #: exercise these steps without touching the real home directory.
        self.home = (Path(config_home).parent if config_home
                     else Path.home())
        self.dry_run = dry_run
        #: Are we writing to the real home directory (tests pass config_home).
        self._live_home = config_home is None

        self._installed: set[str] | None = None
        self._installed_lock = threading.Lock()
        #: Primary tools in the previous apply (category id → component id).
        self._last_primaries: dict[str, str] = {}
        #: Backups go to the same folder for a whole apply session.
        self._backup_dir: Path | None = None
        #: Files created from scratch in this session (recorded once).
        self._created: set[Path] = set()
        #: Files skipped in the last write_changed round because of foreign
        #: ownership {relative path: tool name}.
        self._protected: dict[str, str] = {}
        #: WALLPAPER_ROTATE in the previous apply. When rotation is TURNED OFF
        #: no file changes (the unit templates are no longer rendered, existing
        #: files are not deleted either), so the diff stays empty and the timer
        #: would keep running. Only the previous value reveals the turn-off.
        self._last_rotate: str | None = None
        self._last_wallpaper_path: Path | None = None
        #: Were eww widgets on in the last apply (None = not known yet).
        #: When the eww component is dropped no eww file is written; the action
        #: that closes the still-open windows only comes from this difference.
        self._last_eww: bool | None = None

    # -------------------------------------------------------- installed? ----
    def installed_packages(self, refresh: bool = False) -> set[str]:
        """Installed package names + the names they ``Provides``.

        ``pacman -Qq`` alone was not enough: renamed packages carry the old
        name as "provides" (awww → swww, 7zip → p7zip, mesa →
        libva-mesa-driver), and when the catalog or the user asked for the old
        name the component looked "not installed" FOREVER — render skipped that
        section and doctor reported a bogus error. Gives the same meaning as
        ``pacman -T``; read once and cached.
        """
        if self._installed is None or refresh:
            with self._installed_lock:
                if self._installed is None or refresh:
                    names = _read_pacman_local_db()
                    if not names:
                        try:
                            out = subprocess.run(["pacman", "-Qi"], capture_output=True,
                                                 text=True, timeout=60, check=False,
                                                 env={**os.environ, "LC_ALL": "C"}).stdout
                            names = _parse_installed(out)
                        except (OSError, subprocess.SubprocessError):
                            # No pacman (non-Arch / test environment): we cannot verify,
                            # treat every component as installed —
                            # lib/render.sh:_render_component_installed makes the same call.
                            names = set()
                    self._installed = names
        return self._installed

    def component_installed(self, comp_id: str) -> bool:
        """Are ALL of the component's packages installed?

        Counterpart of ``lib/render.sh:_render_component_installed``. If pacman
        could not be read (empty set) nothing can be verified and the selection
        is accepted as is — otherwise nothing would be generated outside Arch.
        """
        installed = self.installed_packages()
        if not installed:
            return True
        comp = self.catalog.component(comp_id)
        if comp is None:
            return False
        packages = list(comp.repo) + list(comp.aur)
        return all(pkg in installed for pkg in packages)

    def missing_packages(self, comp_id: str) -> list[str]:
        """The component's missing packages — for the UI's ``pacman -S`` hint."""
        installed = self.installed_packages()
        if not installed:
            return []
        comp = self.catalog.component(comp_id)
        if comp is None:
            return []
        return [p for p in list(comp.repo) + list(comp.aur) if p not in installed]

    # ------------------------------------------------- collecting variables -
    def export_vars(self, values: dict[str, str],
                    selected: Iterable[str]) -> tuple[dict[str, str], list[str]]:
        """Variables for the templates + components with missing packages.

        Counterpart of ``lib/render.sh:render_export_vars``. For a component
        whose package is not installed ``HAS_*``/``EXEC_*`` are NOT written at
        all: if they were, a keybinding depending on that component via
        ``require`` (e.g. audio-mixer) would be bound to a command that does
        not work, and since Hyprland resolves a second bind on the same key by
        the last line, it could also replace another keybinding.
        """
        out = dict(values)
        skipped: list[str] = []

        # The variable of single-choice categories (BAR, TERMINAL, LAUNCHER,
        # NOTIFIER, WALLPAPER_DAEMON…) is derived FROM THE SELECTION and
        # OVERRIDES the value here — exactly the same rule as
        # install.sh:selection_resolve_primaries.
        #
        # Without this line the settings app generated NO bar/terminal/launcher
        # config: templates start with "require: BAR==waybar && HAS_WAYBAR",
        # while on the GUI side BAR was never defined (to_conf fills it from
        # primaries when writing settings.conf, but it is missing from the
        # in-memory values). The condition silently stayed false, the
        # waybar/hyprpanel/quickshell/wayle files were never written and the
        # user said "I applied the profile, the bar didn't change". The override
        # direction matters: even if the profile says "BAR=quickshell-bar", the
        # template must follow whichever backend is really installed/selected.
        out.update(self.catalog.primary_vars(list(selected)))

        # If WALLPAPER_PATH is empty, THEME="auto" extraction silently fails
        # (render:_auto_palette sees an empty path and gives up) and the colors
        # fall back to the default palette. The same path the wallpaper step
        # uses is written — if the two looked in different places the palette
        # would come from a different image.
        if not out.get("WALLPAPER_PATH"):
            out["WALLPAPER_PATH"] = str(self.wallpaper_file(values))

        for name, value in self._gpu_vars().items():
            out.setdefault(name, value)
        # The "Souprland logo" option of the terminal startup screen (fastfetch).
        # Mark without a background: the terminal draws it over its own theme;
        # with dark block-character styles it turned into dot noise.
        out["SOUPRLAND_LOGO"] = str(self.root / "assets" / "souprland-mark.png")

        # If the active rice adds lines to Hyprland (starting eww,
        # keybindings) it installs its own ~/.config/hypr/rice.conf;
        # hyprland.conf only sources it when the file exists — without it the
        # "source" line would be an error in Hyprland.
        out["RICE_HYPR"] = "1" if (self.config_home / "hypr/rice.conf").is_file() else ""
        # hyprpaper 0.8 changed its config syntax (wallpaper { } blocks, no
        # preload); if an old version is installed, the old syntax.
        out["HYPRPAPER_LEGACY"] = "1" if self._hyprpaper_legacy() else ""
        # The Lua-mode counterpart (hyprland.lua → require("rice")).
        out["RICE_HYPR_LUA"] = "1" if (self.config_home / "hypr/rice.lua").is_file() else ""
        # Mix parts (mix.py): startup lines (mix.conf) and the commands bound
        # to the user's keys (MIX_OVERRIDE_*).
        from . import mix as mix_mod
        out.update(mix_mod.render_vars(self.home))

        # HYPR_LANG="auto" CANNOT go to the templates: the hypr templates'
        # condition tests equality like "HYPR_LANG==conf" (or ==lua), "auto"
        # matches neither and NO Hyprland config is generated — window
        # borders/shadows keep the old color while waybar, kitty, GTK etc. are
        # refreshed ("the colors at the corners don't change"). On the bash
        # side lib/preflight.sh:preflight_detect_hypr_lang resolves this at the
        # start of the install; the settings app had no counterpart, and since
        # it stays "auto" in settings.conf the same gap appeared every round.
        out["HYPR_LANG"] = self.resolve_hypr_lang(values.get("HYPR_LANG", ""))

        # If a tool like nwg-displays generates monitors.conf/workspaces.conf
        # itself, those files are NOT rendered at all. write_changed's protection
        # alone was not enough: the file would be rendered every round and
        # skipped as "changed", and the user would see the same warning on
        # every settings change.
        #
        # Only in conf mode: in lua mode hyprland.lua requires monitors.lua
        # with "{{#if MANAGE_MONITORS}}" — emptying the variable would not just
        # skip generating the file, it would also stop the foreign tool's file
        # from being read at all. There the protection comes from write_changed.
        if out["HYPR_LANG"] == "conf":
            owners = self.foreign_owners()
            if "hypr/monitors.conf" in owners:
                out["MANAGE_MONITORS"] = ""
            if "hypr/workspaces.conf" in owners:
                out["WORKSPACE_MONITOR_MAP"] = ""

        for comp_id in selected:
            if not self.component_installed(comp_id):
                skipped.append(comp_id)
                continue
            key = comp_id.replace("-", "_").upper()
            out[f"HAS_{key}"] = "1"
            comp = self.catalog.component(comp_id)
            if comp is not None and comp.exec:
                out[f"EXEC_{key}"] = comp.exec
        return out, skipped

    def resolve_hypr_lang(self, value: str) -> str:
        """``auto`` → ``conf`` or ``lua`` depending on the installed Hyprland version.

        Same rule as lib/preflight.sh:preflight_detect_hypr_lang: from 0.57 on
        (and on hyprland-git) the .conf parser was removed, so Lua is
        generated; below that, classic .conf. If the version cannot be read,
        .conf — generating the old format is always better than generating
        nothing.
        """
        wanted = (value or "auto").strip().lower()
        if wanted in ("conf", "lua"):
            return wanted

        version = ""
        if shutil.which("hyprctl"):
            try:
                out = subprocess.run(["hyprctl", "version"], capture_output=True,
                                     text=True, timeout=5).stdout
            except (OSError, subprocess.SubprocessError):
                out = ""
            for line in out.splitlines():
                if line.startswith("Hyprland"):
                    parts = line.split()
                    if len(parts) > 1:
                        version = parts[1]
                    break
        if not version and shutil.which("pacman"):
            try:
                if subprocess.run(["pacman", "-Qq", "hyprland-git"],
                                  capture_output=True, timeout=5).returncode == 0:
                    return "lua"            # git build: main branch
                out = subprocess.run(["pacman", "-Q", "hyprland"],
                                     capture_output=True, text=True,
                                     timeout=5).stdout.split()
                if len(out) > 1:
                    version = out[1]
            except (OSError, subprocess.SubprocessError):
                version = ""

        version = version.lstrip("v").split("-")[0]
        try:
            major, minor = (int(part) for part in (version.split(".") + ["0"])[:2])
        except ValueError:
            return "conf"
        return "lua" if (major >= 1 or (major == 0 and minor >= 57)) else "conf"

    @staticmethod
    def _hyprpaper_legacy() -> bool:
        """Is the installed hyprpaper older than 0.8 (same rule as lib/render.sh)?
        If not installed, the new version will be installed: no."""
        if not shutil.which("pacman"):
            return False
        try:
            out = subprocess.run(["pacman", "-Q", "hyprpaper"], capture_output=True,
                                 text=True, timeout=5).stdout.split()
        except (OSError, subprocess.SubprocessError):
            return False
        if len(out) < 2:
            return False                     # missing or hyprpaper-git
        version = out[1].split(":")[-1].split("-")[0]
        try:
            major, minor = (int(p) for p in (version.split(".") + ["0"])[:2])
        except ValueError:
            return False
        return (major, minor) < (0, 8)

    @staticmethod
    def _gpu_vars() -> dict[str, str]:
        """HAS_NVIDIA/AMD/INTEL — counterpart of lib/preflight.sh:check_gpu."""
        out = {"HAS_NVIDIA": "", "HAS_AMD": "", "HAS_INTEL": ""}
        try:
            listing = subprocess.run(["lspci"], capture_output=True, text=True,
                                     timeout=10, check=False).stdout.lower()
        except (OSError, subprocess.SubprocessError):
            return out
        if "nvidia" in listing:
            out["HAS_NVIDIA"] = "1"
        if "amd/ati" in listing or "advanced micro devices" in listing:
            out["HAS_AMD"] = "1"
        if "intel" in listing and ("vga" in listing or "display" in listing):
            out["HAS_INTEL"] = "1"
        return out

    # ------------------------------------------------------------- write ---
    def _session_backup_dir(self) -> Path:
        """This session's backup directory; created on first use, old ones pruned."""
        if self._backup_dir is None:
            # self.home: when tests/dry-run pass config_home, the backup goes
            # there too — it does not leak into the real home directory.
            self._backup_dir = backups_mod.new_dir("live", self.home)
            backups_mod.prune(backups_mod.root(self.home))
        return self._backup_dir

    def _backup(self, target: Path) -> None:
        """Counterpart of ``lib/core.sh:backup_path`` — before overwriting.

        The applier lives for a whole GUI session and writes the same file many
        times. The backup is taken ONLY the first time: it used to be copied
        over on every write, so the backup held the state before the last
        write rather than the state at session start.
        """
        if not target.exists() and not target.is_symlink():
            return
        try:
            rel = target.relative_to(self.home)
        except ValueError:
            rel = Path("_root") / target.relative_to("/")
        dest = self._session_backup_dir() / rel
        if dest.exists() or dest.is_symlink():
            return
        dest.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.copy2(target, dest)
        except OSError:
            pass  # failing to back up is no reason to stop applying

    def foreign_owners(self) -> dict[str, str]:
        """Which of the protected targets are held by another tool?

        {relative path: tool name}. Empty dict = all ours (or none exist).
        """
        owners: dict[str, str] = {}
        for rel in PROTECTED_TARGETS:
            owner = foreign_owner(self.config_home / rel)
            if owner:
                owners[rel] = owner
        return owners

    def release_foreign(self, rel: str) -> str | None:
        """Takes management of a foreign tool's file back to THIS tool.

        Called when the user says "let this tool manage monitors.conf" in the
        UI: since foreign_owner detection looks at the existing file, no render
        can change it while the file is in place. The file is first backed up
        (~/.config/hyprsetup-backups/), then deleted; the next apply round
        writes a new one carrying our own marker.

        Returns: the name of the tool that generated the file (if anything
        was done), otherwise ``None``.
        """
        if rel not in PROTECTED_TARGETS:
            return None
        target = self.config_home / rel
        owner = foreign_owner(target)
        if owner is None or self.dry_run:
            return None
        self._backup(target)
        try:
            target.unlink()
        except OSError:
            return None
        return owner

    def _keybind_combos(self, variables: dict[str, str]) -> list[str]:
        """All keybinding keys this project knows (MOD+X), even if not generated.

        Keybindings whose condition is not met (e.g. audio tools not selected
        because the rice brings them) are not generated; those keys must keep
        the author's function, otherwise once the author's was removed too the
        volume/brightness keys were left dead.
        """
        if not self.keybinds:
            return []
        overrides = keybinds_mod.parse_overrides(variables.get("KEYBINDS", ""))
        combos = []
        for bind in self.keybinds.all():
            for combo in (bind.keys, overrides.get(bind.id, "")):
                if not combo:
                    continue
                # The switcher's ALT-release binding is ours too: with the
                # switcher off, the author's binding on the same key (their own alt-tab) must stay.
                extra = (keybinds_mod.release_combos(
                    combo, variables.get("MOD_KEY", "SUPER"))
                    if bind.id == keybinds_mod.SWITCHER_BIND else [])
                for item in (combo, *extra):
                    if item not in combos:
                        combos.append(item)
        return combos

    def _stage_rice_overlay(self, staging: Path, owned: list[Path]) -> set[str]:
        """Keybinding layer when a rice owns ~/.config/hypr.

        The generated keybinds.conf cannot be written into the author's folder
        (it is owned), but if skipped, the keybindings revert to the author's on
        a profile switch and modules like ALT+Tab are lost. Instead two layer
        files (conf + Lua; rice.py hooks them onto the end of the author's main
        file) and copies of the scripts that do not clash with the author's
        scripts/ folder are put into staging. The returned paths are written
        even though they are owned.
        """
        hypr = self.config_home / "hypr"
        staged = staging / "hypr" / "keybinds.conf"
        whole = bool(owned) and rice_mod.is_owned(hypr / "keybinds.conf", owned)
        # rice.conf mode (athena, vantage): the hypr folder is the user's; the
        # layer is loaded after rice.conf in hyprland.conf, scripts stay in place.
        partial = bool(owned) and not whole and rice_mod.is_owned(hypr / "rice.conf", owned)
        if not (whole or partial) or not staged.is_file():
            # No rice: a layer left over from rice.conf mode is no longer loaded.
            if not owned and not self.dry_run:
                for name in (keybinds_mod.RICE_OVERLAY_CONF, keybinds_mod.RICE_OVERLAY_LUA):
                    (hypr / name).unlink(missing_ok=True)
            return set()
        text = staged.read_text(encoding="utf-8")
        keyboard: dict[str, str] = {}
        for main in ("hyprland.conf", "hyprland.lua"):
            if (staging / "hypr" / main).is_file():
                keyboard = keybinds_mod.keyboard_settings(
                    (staging / "hypr" / main).read_text(encoding="utf-8"))
                if keyboard:
                    break
        rules: dict[str, list[str]] = {}
        for lang, rel in (("conf", "windowrules.conf"), ("lua", "hyprland/windowrules.lua")):
            path = staging / "hypr" / rel
            rules[lang] = (keybinds_mod.app_window_rules(path.read_text(encoding="utf-8"), lang)
                           if path.is_file() else [])
        if not rules["lua"] and rules["conf"]:
            rules["lua"] = keybinds_mod.window_rules_to_lua(rules["conf"])
        rice_conf = hypr / "rice.conf"
        rice_text = (rice_conf.read_text(encoding="utf-8", errors="ignore")
                     if rice_conf.is_file() else "")
        lock_binds = keybinds_mod.lock_key_binds(rice_text)
        author_keys = keybinds_mod.author_key_spellings(rice_text)
        clear_binds = keybinds_mod.author_binds(rice_text)
        if partial:
            made = set()
            for name, lang in ((keybinds_mod.RICE_OVERLAY_CONF, "conf"),
                               (keybinds_mod.RICE_OVERLAY_LUA, "lua")):
                (staging / "hypr" / name).write_text(
                    keybinds_mod.rice_overlay(text, lang, move_scripts=False,
                                              keyboard=keyboard, window_rules=rules[lang],
                                              lock_binds=lock_binds, author_keys=author_keys,
                                          clear_binds=clear_binds,
                                          known_combos=getattr(self, "_known_combos", [])),
                    encoding="utf-8")
                made.add(f"hypr/{name}")
            return made
        autostart = staging / "hypr" / "autostart.conf"
        autostart_text = autostart.read_text(encoding="utf-8") if autostart.is_file() else ""
        # The author's hypr does not read this project's autostart.conf: our
        # own scripts that must run at session start are moved into the layer.
        preload: list[str] = []
        for command in ("~/.config/hypr/scripts/windowswitch.py --preload",
                        "~/.config/hypr/scripts/visualizer.sh start",
                        "~/.config/hypr/scripts/gamemode.py watch",
                        "~/.config/hypr/scripts/notifylog.py run",
                        "~/.config/hypr/scripts/dock.sh start"):
            if command in autostart_text:
                preload.append(keybinds_mod.rice_script_paths(command))
        # Submaps the author keeps permanently active (caelestia: on every load
        # "exec = hyprctl dispatch submap global"): keybindings are written there too.
        submaps: list[str] = []
        conf_texts: list[str] = []
        for conf in sorted(hypr.resolve().rglob("*.conf")):
            if conf.name == keybinds_mod.RICE_OVERLAY_CONF:
                continue
            try:
                conf_text = conf.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            found = re.findall(r"dispatch\s+submap\s+([A-Za-z0-9_.-]+)", conf_text)
            submaps += [n for n in found if n != "reset" and n not in submaps]
            conf_texts.append(conf_text)
        for lua_file in sorted(hypr.resolve().rglob("*.lua")):
            if lua_file.name == keybinds_mod.RICE_OVERLAY_LUA:
                continue
            try:
                conf_texts.append(lua_file.read_text(encoding="utf-8", errors="ignore"))
            except OSError:
                continue
        lock_binds = keybinds_mod.lock_key_binds("\n".join(conf_texts))
        author_keys = keybinds_mod.author_key_spellings("\n".join(conf_texts))
        clear_binds = keybinds_mod.author_binds("\n".join(conf_texts), submaps)
        made: set[str] = set()
        for name, lang in ((keybinds_mod.RICE_OVERLAY_CONF, "conf"),
                           (keybinds_mod.RICE_OVERLAY_LUA, "lua")):
            (staging / "hypr" / name).write_text(
                keybinds_mod.rice_overlay(text, lang, preload, submaps=submaps,
                                          keyboard=keyboard, window_rules=rules[lang],
                                          lock_binds=lock_binds, author_keys=author_keys,
                                          clear_binds=clear_binds,
                                          known_combos=getattr(self, "_known_combos", [])),
                encoding="utf-8")
            made.add(f"hypr/{name}")
        scripts = staging / "hypr" / "scripts"
        for src in sorted(scripts.rglob("*")) if scripts.is_dir() else []:
            if not src.is_file():
                continue
            target = staging / "hypr" / keybinds_mod.RICE_SCRIPTS / src.relative_to(scripts)
            target.parent.mkdir(parents=True, exist_ok=True)
            try:
                target.write_text(keybinds_mod.rice_script_paths(
                    src.read_text(encoding="utf-8")), encoding="utf-8")
            except UnicodeDecodeError:
                target.write_bytes(src.read_bytes())
            target.chmod(src.stat().st_mode & 0o7777)
            made.add(str(target.relative_to(staging)).replace(os.sep, "/"))
        return made

    #: First lines of templates/hypr-lua/hyprland.lua.tmpl's output.
    _GENERATED_LUA_MARK = "generated by hyprsetup (Lua config)"

    def _retire_generated_lua(self) -> bool:
        """Removes a hyprland.lua this project generated, once conf is generated.

        Hyprland 0.56 already reads hyprland.lua and prefers it over
        hyprland.conf. After HYPR_LANG went lua → conf/auto the old generated
        file stayed, so the next login loaded that stale Lua config and every
        later settings change (written to .conf) silently did nothing. An
        author's own hyprland.lua (rice) and the conf bridge are left alone.
        True if the file was removed.
        """
        lua = self.config_home / "hypr" / "hyprland.lua"
        if not lua.is_file():
            return False
        try:
            with open(lua, encoding="utf-8", errors="ignore") as f:
                head = f.read(512)
        except OSError:
            return False
        if self._GENERATED_LUA_MARK not in head:
            return False
        owned = rice_mod.owned_paths(self.home)
        if owned and rice_mod.is_owned(lua, owned):
            return False
        if not self.dry_run:
            self._backup(lua)
            lua.unlink()
        return True

    def _retire_root_quickshell(self) -> bool:
        """Removes the shell.qml older versions generated in ~/.config/quickshell/.

        A shell.qml in Quickshell's base folder makes it ignore every named
        config: a rice/mix bar started with ``qs -c <name>`` printed "Could
        not find config" and never opened (vantage). Ours now lives in
        quickshell/hyprsetup/; an author's own root shell.qml is left alone.
        True if the file was removed.
        """
        qml = self.config_home / "quickshell" / "shell.qml"
        try:
            with open(qml, encoding="utf-8", errors="ignore") as f:
                head = f.read(256)
        except OSError:
            return False
        if "generated by hyprsetup" not in head:
            return False
        owned = rice_mod.owned_paths(self.home)
        if owned and rice_mod.is_owned(qml, owned):
            return False
        if not self.dry_run:
            self._backup(qml)
            qml.unlink()
        return True

    def write_changed(self, staging: Path) -> list[str]:
        """Copies ONLY the differing files from the staging tree to ~/.config.

        The returned list feeds the action mapping. Called a second time with
        the same content it returns an empty list (idempotency) — this
        guarantees no "apply → daemon restarts → apply" loop forms.
        """
        written: list[str] = []
        self._protected = {}
        # If a rice (rice.py) is active, the paths it owns are the author's
        # files: if template output were written over them, the rice would
        # break on the first settings change.
        owned = rice_mod.owned_paths(self.home)
        overlay = self._stage_rice_overlay(staging, owned)
        for src in sorted(staging.rglob("*")):
            if not src.is_file():
                continue
            rel = src.relative_to(staging)
            dest = self.config_home / rel
            if (owned and rice_mod.is_owned(dest, owned)
                    and str(rel).replace(os.sep, "/") not in overlay):
                self._protected[str(rel).replace(os.sep, "/")] = "rice"
                continue

            # A monitor file generated by another tool (nwg-displays) is NEVER
            # overwritten — the user's monitor layout there would be silently
            # wiped. export_vars already skips rendering these files; this is
            # the safety belt (e.g. lua mode).
            rel_text = str(rel).replace(os.sep, "/")
            if rel_text in PROTECTED_TARGETS:
                owner = foreign_owner(dest)
                if owner:
                    self._protected[rel_text] = owner
                    continue

            new = src.read_bytes()
            if dest.is_file():
                try:
                    current = dest.read_bytes()
                    if current == new or (rel_text in KCONFIG_TARGETS
                                          and _kconfig_covers(current, new)):
                        continue
                except OSError:
                    pass

            written.append(str(rel).replace(os.sep, "/"))
            if self.dry_run:
                continue

            if dest.exists() or dest.is_symlink():
                self._backup(dest)
            elif dest not in self._created:
                # Did not exist before: a restore must DELETE it (see backups.py).
                self._created.add(dest)
                backups_mod.record_created(self._session_backup_dir(), dest)
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(new)
            # Permissions come from the template's {{! mode: 755 }} directive.
            dest.chmod(src.stat().st_mode & 0o7777)
        return written

    # ------------------------------------------------------------- apply ---
    def apply(self, values: dict[str, str],
              selected: Iterable[str]) -> ApplyResult:
        """Render, write what changed, refresh the affected daemons."""
        selected = list(selected)
        # If the active rice brings a category itself (e.g. its own eww bar)
        # this project's component in that category is not started and its
        # config is not generated: no two bars on screen.
        provided = set(rice_mod.provided_categories(self.home))
        if provided:
            selected = [c for c in selected
                        if (self.catalog.category_of(c) is None
                            or self.catalog.category_of(c).id not in provided)]
        result = ApplyResult()

        # The wallpaper is put in place BEFORE RENDERING, for two reasons:
        #   1. The profile brings its own image (WALLPAPER_IMAGE); if not copied,
        #      the profile is applied but the old image stays on the desktop.
        #   2. THEME="auto" extracts the palette from that file (render:_auto_palette).
        #      If the file is not in place, extraction fails and the colors
        #      silently fall back to the default palette — the source of the
        #      "I applied the profile, the colors didn't come" complaint.
        #      install.sh does this with wallpaper_step before rendering; the
        #      app side had no counterpart.
        wallpaper_note = self._wallpaper_step(values)

        variables, result.skipped = self.export_vars(values, selected)
        # Actions (restarting bar/notifications/wallpaper) look at
        # BAR/NOTIFIER/WALLPAPER_DAEMON DERIVED from the selection; the raw
        # settings lack them. With raw values _restart_bar killed every bar and
        # started none, and the wallpaper and notification daemons were never
        # refreshed (in a mix the wallpaper changed but the old one stayed on screen).
        values = {**values, **{k: variables[k] for k in self._PRIMARY_CATEGORIES.values()
                               if variables.get(k)}}

        with tempfile.TemporaryDirectory(prefix="hyprsetup-apply-") as tmp:
            staging = Path(tmp)
            try:
                render_mod.render_tree(
                    templates_dir=self.templates, out_dir=staging,
                    variables=variables, catalog=self.catalog,
                    selected=selected, keybinds=self.keybinds)
            except Exception as exc:                      # noqa: BLE001
                result.errors.append(f"Could not render templates: {exc}")
                return result
            self._known_combos = self._keybind_combos(variables)
            result.written = self.write_changed(staging)
            result.protected = dict(self._protected)
        if variables.get("HYPR_LANG") == "conf" and self._retire_generated_lua():
            result.written.append("hypr/hyprland.lua")
        if self._retire_root_quickshell():
            result.written.append("quickshell/shell.qml")

        actions = self._actions_for(result.written, values)
        eww_on = self._eww_wanted(values, selected)
        if (self._last_eww is not None and self._last_eww != eww_on
                and "eww" not in actions):
            actions = [a for a in _ACTION_ORDER
                       if a in actions or a == "eww"]
        # The wallpaper file is written outside ~/.config so it does not show up
        # in written; if it changed, the daemon still needs a refresh.
        if wallpaper_note and "wallpaper" not in actions:
            actions = list(actions) + ["wallpaper"]
        if self.dry_run:
            result.actions = [ACTION_LABELS.get(a, a) for a in actions]
            if wallpaper_note:
                result.actions.insert(0, wallpaper_note)
            self._remember_primaries(values)
            self._last_eww = eww_on
            return result

        # A session started with Lua does not read the conf config: keybindings
        # are loaded through the temporary hyprland.lua bridge (rice.sync_conf_bridge).
        if rice_mod.sync_conf_bridge(self.home, reload=False) and "hypr" not in actions:
            actions = [a for a in _ACTION_ORDER if a in actions or a == "hypr"]

        for action in actions:
            try:
                self._run_action(action, values, selected)
            except Exception as exc:                      # noqa: BLE001
                result.errors.append(f"{ACTION_LABELS.get(action, action)}: {exc}")
            else:
                result.actions.append(ACTION_LABELS.get(action, action))

        if wallpaper_note:
            result.actions.insert(0, wallpaper_note)
        qs_note = self._sync_quickshell_widgets(values, selected)
        if qs_note:
            result.actions.append(qs_note)
        if self._theme_schedule_pending(values) and "systemd" not in actions:
            # THEME_DAY/THEME_NIGHT are written to no file, so changing the
            # night theme at night used to wait for the next switch time.
            _run(["systemctl", "--user", "start", "--no-block", "hyprsetup-theme.service"])
            result.actions.append("Day/night theme updated")
        note = (self._sync_installed_copy()
                if render_mod.truthy(values.get("SELFUPDATE_SYNC", "true")) else "")
        if note:
            result.actions.append(note)
        self._remember_primaries(values)
        self._last_eww = eww_on
        return result

    #: Our own Quickshell config (widgets, and the bar when BAR=quickshell-bar).
    _QS_SHELL = "quickshell/hyprsetup/shell.qml"

    def _sync_quickshell_widgets(self, values: dict[str, str], selected: list[str]) -> str:
        """Starts/stops this project's Quickshell widgets in the running session.

        eww had _refresh_eww; Quickshell had nothing, so picking it as the
        widget engine (or adding widgets) showed nothing until the next login.
        Once running, Quickshell reloads shell.qml by itself on every change.
        The bar case (BAR=quickshell-bar) belongs to _restart_bar. Only the
        process running OUR file is touched — a rice's "qs -c …" is not.
        """
        if (self.dry_run or not self._live_home or not self._session_live()
                or values.get("BAR") == "quickshell-bar"):
            return ""
        path = self.config_home / self._QS_SHELL
        wanted = ("quickshell" in selected and self.component_installed("quickshell")
                  and path.is_file()
                  and bool(render_mod.active_widgets(values, selected, "quickshell")))
        running = _run(["pgrep", "-u", str(os.getuid()), "-f", f"quickshell -p {path}$"])
        if wanted and not running:
            _spawn(f"quickshell -p {shlex.quote(str(path))}")
            return "Quickshell widgets started"
        if not wanted and running:
            _run(["pkill", "-u", str(os.getuid()), "-f", f"quickshell -p {path}$"])
            return "Quickshell widgets stopped"
        return ""

    def _theme_schedule_pending(self, values: dict[str, str]) -> bool:
        """Is the schedule on while the current theme is not the one it wants now?"""
        if (not self._live_home or not self._session_live()
                or not render_mod.truthy(values.get("THEME_SCHEDULE", "false"))):
            return False
        from . import themeschedule
        return bool(themeschedule.changes(values))

    def _sync_installed_copy(self) -> str:
        """When applied from the repo, syncs the installed copy (~/.local/share/hyprsetup).

        The bar panel, MOD+I and the keybinding cheat sheet run from the
        installed copy. Without syncing, the repo's changes are not visible and
        the first settings change made from MOD+I renders the old templates and
        reverts the files written from the repo. Only done in the real home
        directory and when the copy is already installed.
        """
        from . import selfupdate
        if (self.dry_run or not self._live_home or not selfupdate.installed()
                or not selfupdate.is_source_tree(self.root)):
            return ""
        try:
            changed = selfupdate.sync(self.root)
        except OSError as exc:
            return f"Could not update the installed app: {exc}"
        return f"Installed app updated ({len(changed)} files)" if changed else ""

    # ---------------------------------------------------------- wallpaper ---
    def wallpaper_file(self, values: dict[str, str]) -> Path:
        """``WALLPAPER_PATH`` — the real file path with "~" expanded."""
        raw = values.get("WALLPAPER_PATH", "") or "~/Pictures/wallpapers/wallpaper.png"
        if raw.startswith("~"):
            return self.home / raw.lstrip("~/")
        return Path(raw).expanduser()

    def _wallpaper_is_ours(self, target: Path) -> bool:
        """Is the file one of the generated images shipped in the repo?

        Same rule as install.sh:_wallpaper_is_ours (content comparison): if
        the user put their own image there, the profile does NOT override it.
        Size is checked first; only a candidate matching in size is read.
        """
        from . import wallpaper as wallpaper_mod
        if wallpaper_mod.is_generated(target):
            return True
        try:
            size = target.stat().st_size
        except OSError:
            return False
        data = None
        # Include every bundled source format so a wallpaper copied by one
        # profile can still be replaced by the next one.
        wallpapers = self.root / "wallpapers"
        for candidate in [*wallpapers.glob("*.png"), *wallpapers.glob("profile/*.jpg")]:
            try:
                if candidate.stat().st_size != size:
                    continue
                data = target.read_bytes() if data is None else data
                if candidate.read_bytes() == data:
                    return True
            except OSError:
                continue
        return photos.is_archived_wallpaper(self.root, target, size)

    def _wallpaper_step(self, values: dict[str, str]) -> str:
        """Puts the profile's wallpaper in place; returns what was done.

        Precedence is the same as install.sh:wallpaper_step: first the ready
        image in the repo (WALLPAPER_IMAGE), otherwise generation from a
        pattern (WALLPAPER_STYLE). The user's own image is preserved.
        """
        target = self.wallpaper_file(values)
        image = (values.get("WALLPAPER_IMAGE", "") or "").strip()
        style = (values.get("WALLPAPER_STYLE", "") or "").strip()
        if not image and not style:
            return ""
        if self.dry_run:
            # --dry-run touches no file; that is why render sees the old
            # wallpaper too (and so does the THEME="auto" guess).
            return f"[dry-run] wallpaper: {target}"
        if target.exists() and not self._wallpaper_is_ours(target):
            return ""                       # your own image, left alone

        if image:
            source = photos.resolve(self.root, image)
            if source is not None:
                try:
                    if (target.exists()
                            and target.read_bytes() == source.read_bytes()):
                        return ""           # already the same file
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(source, target)
                except OSError as exc:                    # noqa: BLE001
                    return f"Could not copy wallpaper: {exc}"
                return "Wallpaper updated"

        if not style:
            return ""
        from . import wallpaper as wallpaper_mod
        theme = values.get("THEME", "") or themes.DEFAULT
        if theme == "auto":
            # "auto" extracts the palette from the wallpaper; when generating
            # from a pattern we cannot do the reverse, so the default palette is used.
            theme = themes.DEFAULT
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            wallpaper_mod.generate(theme, style, target,
                                   overrides=values.get("CUSTOM_COLORS", ""))
        except (OSError, ValueError) as exc:              # noqa: BLE001
            return f"Could not generate wallpaper: {exc}"
        return f"Wallpaper generated ({style})"

    #: Categories watched to catch a primary tool change.
    _PRIMARY_CATEGORIES = {"bar": "BAR", "notify": "NOTIFIER",
                           "wallpaper": "WALLPAPER_DAEMON"}

    def seed_state(self, values: dict[str, str],
                   selected: Iterable[str]) -> None:
        """Seeds previous-apply tracking from the state loaded at startup.

        Without this, switching a primary backend (e.g. hyprpaper →
        wallpaperengine when applying st-gozcu / st-kule) on the very first
        apply after opening the GUI sees ``previous is None``: if the target's
        config/script on disk already matches, the daemon switch never runs.
        """
        selected = list(selected)
        primaries = self.catalog.primary_vars(selected)
        merged = {**values, **{k: primaries[k] for k in self._PRIMARY_CATEGORIES.values()
                               if primaries.get(k)}}
        self._remember_primaries(merged)
        self._last_eww = self._eww_wanted(merged, selected)

    def _remember_primaries(self, values: dict[str, str]) -> None:
        for cat, var in self._PRIMARY_CATEGORIES.items():
            self._last_primaries[cat] = values.get(var, "")
        self._last_rotate = (values.get("WALLPAPER_ROTATE") or "0").strip()
        self._last_wallpaper_path = self.wallpaper_file(values)

    def _wallpaper_script(self, name: str) -> Path | None:
        for rel in (f"hypr/scripts/{name}", f"hypr/{keybinds_mod.RICE_SCRIPTS}/{name}"):
            path = self.config_home / rel
            if path.is_file():
                return path
        return None

    def _wallpaper_out_of_sync(self, values: dict[str, str]) -> bool:
        """True if the running wallpaper daemon disagrees with WALLPAPER_DAEMON.

        When switching to a Wallpaper Engine profile (st-gozcu / st-kule) whose
        wallpaperengine.sh on disk already has the same scene ID, write_changed()
        reports no file diff. If another wallpaper daemon is still running — or
        linux-wallpaperengine is not running at all — the wallpaper action must
        still run so the old daemon stops and the scene starts.
        """
        if "wallpaper" in rice_mod.provided_categories(self.home):
            return False
        daemon = values.get("WALLPAPER_DAEMON", "")
        if not daemon:
            return False
        category = next((c for c in self.catalog.categories if c.id == "wallpaper"), None)
        for comp in (category.components if category else []):
            if comp.id == daemon or not comp.exec:
                continue
            if _process_running(comp.exec.split()[0]):
                return True
        if daemon != "wallpaperengine" and _process_running(_WPENGINE_PROCESS):
            return True
        if daemon == "wallpaperengine":
            from . import wpengine
            main_id = (values.get("WPENGINE_ID") or "").strip()
            per_screen = wpengine.parse_per_screen(values.get("WPENGINE_PER_SCREEN", ""))
            if ((main_id or per_screen)
                    and self._wallpaper_script("wallpaperengine.sh") is not None
                    and self.component_installed("wallpaperengine")
                    and not _process_running(_WPENGINE_PROCESS)):
                return True
        return False

    def _actions_for(self, written: Iterable[str],
                     values: dict[str, str]) -> list[str]:
        """Set of actions from the written files + backend changes."""
        actions: set[str] = set()
        for rel in written:
            action = action_for(rel)
            if action:
                actions.add(action)

        # awww reads the image via its client, so a path change may only affect
        # wallpaper.sh and leave the daemon's config untouched.
        if (values.get("WALLPAPER_DAEMON") == "swww" and self._last_wallpaper_path is not None
                and self._last_wallpaper_path != self.wallpaper_file(values)):
            actions.add("wallpaper")

        # A backend change MAY NOT SHOW in the file diff: when switching from
        # waybar to hyprpanel waybar's own config does not change at all, yet
        # it still has to be shut down. So the primary tools are compared
        # separately.
        for cat, var in self._PRIMARY_CATEGORIES.items():
            previous = self._last_primaries.get(cat)
            if previous is not None and previous != values.get(var, ""):
                actions.add({"bar": "bar", "notify": "notifier",
                             "wallpaper": "wallpaper"}[cat])

        # Reconcile the live wallpaper daemon when no config file changed on
        # disk (e.g. re-applying st-gozcu/st-kule with an unchanged
        # wallpaperengine.sh while hyprpaper is still running).
        if (self._live_home and not self.dry_run and self._session_live()
                and "wallpaper" not in actions
                and self._wallpaper_out_of_sync(values)):
            actions.add("wallpaper")

        # When wallpaper rotation is TURNED OFF no file changes; the action
        # that stops the timer only comes from the previous value.
        rotate = (values.get("WALLPAPER_ROTATE") or "0").strip()
        if self._last_rotate is not None and self._last_rotate != rotate:
            actions.add("systemd")

        # Toggling THEME_SCHEDULE does not change any unit file either (the
        # timer is always written), so the timer state is compared directly.
        if self._live_home and not self.dry_run and shutil.which("systemctl"):
            schedule = render_mod.truthy(values.get("THEME_SCHEDULE", "false"))
            if schedule != _timer_enabled("hyprsetup-theme.timer"):
                actions.add("systemd")

        # The cursor theme does not go to a file but straight to hyprctl.
        if any(action_for(rel) == "gtk" for rel in written):
            actions.add("cursor")

        return [a for a in _ACTION_ORDER if a in actions]

    @staticmethod
    def _eww_wanted(values: dict[str, str], selected: list[str]) -> bool:
        """Is the eww engine selected and is at least one widget actually drawn?"""
        return "eww" in selected and bool(
            render_mod.active_widgets(values, selected, "eww"))

    def _refresh_eww(self, values: dict[str, str],
                     selected: list[str]) -> None:
        """Reopens the eww windows with the new config.

        It used to run only "eww reload". That refreshes styles if the daemon
        is already running but does NOT OPEN windows: a user turning on a
        widget or applying a widget set saw nothing on the desktop (and if
        the daemon had not started at login, reload silently did nothing).
        A removed widget's window also stayed open. Now: everything is
        closed, the config is re-read and the active list is opened with
        widgets.sh — the logic that waits for the daemon lives there.
        """
        if shutil.which("eww") is None:
            return
        running = _run(["eww", "ping"])
        were_open = running and bool(_output(["eww", "active-windows"]).strip())
        if running:
            _run(["eww", "close-all"])
        if not self._eww_wanted(values, selected):
            return
        # For a user who does not show them at startup (toggles with MOD+W),
        # don't force widgets open on every color change: in that case only the
        # ones that were just open are reopened.
        if not (render_mod.truthy(values.get("WIDGET_AUTOSTART", "true"))
                or were_open):
            return
        if running:
            _run(["eww", "reload"])
        script = self.config_home / "hypr/scripts/widgets.sh"
        if script.is_file():
            _spawn(f"{shlex.quote(str(script))} show")
        else:
            _spawn("eww daemon")

    # ------------------------------------------------------------ actions -
    #: Actions that can also run in a test/preview home (config_home given):
    #: they only write files under self.home. The rest touch the live session
    #: (kill processes, gsettings, hyprctl…) and are skipped — tools/test.sh's
    #: apply in a temporary directory was closing the user's Wallpaper Engine
    #: and visualizer.
    _OFFLINE_ACTIONS = frozenset({"firefox"})
    #: Actions that (re)start Hyprland-session daemons. Outside Hyprland (the
    #: settings app opened from KDE/GNOME, a TTY) they would put waybar, mako…
    #: on top of the other desktop — the same rule _sync_dock/_sync_script use.
    _SESSION_ACTIONS = frozenset({"bar", "notifier", "wallpaper", "eww", "idle"})

    def _run_action(self, action: str, values: dict[str, str],
                    selected: list[str]) -> None:
        if not self._live_home and action not in self._OFFLINE_ACTIONS:
            return
        if action in self._SESSION_ACTIONS and not self._session_live():
            return
        if action == "hypr":
            self._hyprctl("reload")
        elif action == "bar":
            self._restart_bar(values)
            _reregister_tray_items_later()
        elif action == "notifier":
            # If another notification server is running (the previous theme's)
            # it is stopped and the selected one started: only one can hold the
            # D-Bus name at a time; with swaync left running, the new theme's
            # dunst said "name is acquired" on every start and quit.
            replaced = self._stop_other_notifiers(values.get("NOTIFIER", ""))
            self._restart_primary(values.get("NOTIFIER", ""), always=replaced)
        elif action == "firefox":
            self._apply_firefox_theme()
        elif action == "wallpaper":
            self._refresh_wallpaper(values)
        elif action == "eww":
            self._refresh_eww(values, selected)
        elif action == "idle":
            # hypridle is not part of the "hyprland" component but its own
            # component; it has no exec in the catalog and is managed by name.
            # Also started when not running: a freshly selected hypridle used
            # to stay off until the next login (idle dim/lock did nothing).
            if _process_running("hypridle"):
                _kill_process("hypridle")
                time.sleep(_RESTART_SETTLE)
                _spawn("hypridle")
            elif "hypridle" in selected and self.component_installed("hypridle"):
                _spawn("hypridle")
        elif action == "systemd":
            _run(["systemctl", "--user", "daemon-reload"])
            self._sync_wallpaper_timer(values)
            self._sync_theme_timer(values)
            self._sync_displays_path()
        elif action == "night":
            self._sync_night_shader(values)
        elif action == "visualizer":
            self._sync_script("visualizer.sh")
        elif action == "gamemode":
            self._sync_script("gamemode.py")
        elif action == "notifylog":
            self._sync_script("notifylog.py")
        elif action == "dock":
            self._sync_dock()
        elif action == "actions":
            self._sync_actions()
        elif action == "barpanel":
            self._restart_barpanel()
        elif action == "desktop-db":
            target = Path.home() / ".local/share/applications"
            if target.is_dir():
                _run(["update-desktop-database", str(target)])
        elif action == "gtk":
            self._apply_gsettings(values, selected)
        elif action == "cursor":
            self._apply_cursor(values)
        elif action == "kde":
            self._install_kde_color_scheme()
            self._restart_open_kde_qt_apps()

    def _sync_actions(self) -> None:
        """Has the actions script write its .desktop entries (actions.py desktop)."""
        hypr = self.config_home / "hypr"
        for script in (hypr / "scripts/actions.py",
                       hypr / keybinds_mod.RICE_SCRIPTS / "actions.py"):
            if script.is_file():
                _run([str(script), "desktop"])
                break

    def _restart_barpanel(self) -> None:
        """Restarts the resident bar detail panel with updated theme colors."""
        import signal as signal_mod
        run_dir = Path(os.environ.get("XDG_RUNTIME_DIR") or "/tmp")
        pid_file = run_dir / "hyprsetup-barpanel.pid"
        try:
            pid = int(pid_file.read_text().strip())
            cmdline = Path(f"/proc/{pid}/cmdline").read_bytes()
            if b"barpanel" in cmdline:
                os.kill(pid, signal_mod.SIGTERM)
                time.sleep(0.1)
        except (OSError, ValueError):
            pass
        hypr = self.config_home / "hypr"
        for script in (hypr / "scripts/barpanel.py",
                       hypr / keybinds_mod.RICE_SCRIPTS / "barpanel.py"):
            if script.is_file() and os.access(script, os.X_OK):
                _spawn(f"{shlex.quote(str(script))} --daemon")
                break

    # --- systemd user units -----------------------------------------------
    def _sync_wallpaper_timer(self, values: dict[str, str]) -> None:
        """Enables/disables the wallpaper timer according to WALLPAPER_ROTATE.

        Writing the unit files is not enough: a timer that is not enabled never
        runs. install.sh did this with enable_wallpaper_rotation, the settings
        app had no counterpart — so turning rotation on from the UI did
        nothing, and turning it off left it running.
        """
        unit = "hyprsetup-wallpaper.timer"
        try:
            minutes = int((values.get("WALLPAPER_ROTATE") or "0").strip() or 0)
        except ValueError:
            minutes = 0
        if minutes > 0:
            _run(["systemctl", "--user", "enable", "--now", unit])
        else:
            _run(["systemctl", "--user", "disable", "--now", unit])

    def _sync_theme_timer(self, values: dict[str, str]) -> None:
        """Enables/disables the day/night theme timer according to THEME_SCHEDULE.

        When enabled, the service also runs once right away: if it is already
        night the theme switches without waiting for the next transition.
        """
        unit = "hyprsetup-theme.timer"
        if render_mod.truthy(values.get("THEME_SCHEDULE", "false")):
            _run(["systemctl", "--user", "enable", "--now", unit])
            _run(["systemctl", "--user", "start", "--no-block", "hyprsetup-theme.service"])
        else:
            _run(["systemctl", "--user", "disable", "--now", unit])

    def _sync_displays_path(self) -> None:
        """Monitor file watcher: enable it if the unit file was generated, else disable.

        When nwg-displays changes workspaces.conf, the bar's workspace list is
        regenerated (hyprsetup-displays.path.tmpl).
        """
        unit = "hyprsetup-displays.path"
        if (self.config_home / "systemd/user" / unit).is_file():
            _run(["systemctl", "--user", "enable", "--now", unit])
        else:
            _run(["systemctl", "--user", "disable", "--now", unit])

    def _sync_script(self, name: str) -> None:
        """hypr/scripts/<name> sync: (re)start if the setting is on, otherwise stop."""
        if not self._session_live():
            return
        own = self.config_home / "hypr" / keybinds_mod.RICE_SCRIPTS / name
        script = (own if own.is_file() and rice_mod.is_owned(self.config_home / "hypr",
                                                               rice_mod.owned_paths())
                  else self.config_home / "hypr/scripts" / name)
        if script.is_file():
            _run([str(script), "sync"])

    def _sync_dock(self) -> None:
        """Turns the dock on/off per the setting or restarts it with the new settings."""
        if not self._session_live():
            return
        own = self.config_home / "hypr" / keybinds_mod.RICE_SCRIPTS / "dock.sh"
        script = (own if own.is_file() and rice_mod.is_owned(self.config_home / "hypr",
                                                               rice_mod.owned_paths())
                  else self.config_home / "hypr/scripts/dock.sh")
        if script.is_file():
            _run([str(script), "sync"])

    def _sync_night_shader(self, values: dict[str, str]) -> None:
        """Actually installs the schedule after hyprshade.toml has been written.

        "hyprshade install" generates the systemd user timer (no root
        needed); "hyprshade auto" applies the filter for the current time right
        away, so the setting change is visible without waiting.
        """
        if not shutil.which("hyprshade"):
            return
        # hyprshade 5 only speaks Lua; the generated hyprctl shim translates
        # for a conf session (templates/hypr/scripts/hyprctl-compat/hyprctl).
        shim = self.config_home / "hypr/scripts/hyprctl-compat"
        env = {**os.environ, "PATH": f"{shim}:{os.environ.get('PATH', '')}"}

        def hyprshade(*args: str) -> None:
            try:
                subprocess.run(["hyprshade", *args], capture_output=True, timeout=30,
                               check=False, env=env)
            except (OSError, subprocess.SubprocessError):
                pass
        if not (values.get("NIGHT_SHADER") or "").strip():
            _run(["systemctl", "--user", "disable", "--now", "hyprshade.timer"])
            hyprshade("off")
            return
        hyprshade("install")
        _run(["systemctl", "--user", "daemon-reload"])
        _run(["systemctl", "--user", "enable", "--now", "hyprshade.timer"])
        hyprshade("auto")

    # --- Hyprland ---------------------------------------------------------
    @staticmethod
    def _session_live() -> bool:
        """Is Hyprland really running? (same as install.sh:reload_step)"""
        return bool(os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")) \
            and shutil.which("hyprctl") is not None

    def _hyprctl(self, *args: str) -> None:
        if not self._session_live():
            return
        _run(["hyprctl", *args])

    # --- daemons ----------------------------------------------------------
    def _bar_binaries(self) -> dict[str, str]:
        """Executable name of every component in the bar category."""
        out: dict[str, str] = {}
        for cat in self.catalog.categories:
            if cat.id != "bar":
                continue
            for comp in cat.components:
                if comp.exec:
                    out[comp.id] = comp.exec.split()[0]
        return out

    def _restart_bar(self, values: dict[str, str]) -> None:
        """Restarts the bar; also shuts down the OLD backend.

        Same as install.sh:restart_daemons_step, with two differences:
          · not only waybar/hyprpanel but ALL bar backends in the catalog
            (quickshell-bar, wayle too) are checked;
          · if the widget engine uses the same binary (WIDGET_ENGINE=quickshell
            with BAR=waybar) that binary is kept — otherwise changing the bar
            backend would also kill the desktop widgets.
        """
        active = values.get("BAR", "")
        bars = self._bar_binaries()
        active_bin = bars.get(active, "")
        if active in bars and not self.component_installed(active):
            # The wanted bar is not installed (e.g. "Enable anyway" on a
            # HyprPanel preset): stopping the running bar would leave none.
            return

        protected = set()
        engine = values.get("WIDGET_ENGINE", "")
        engine_comp = self.catalog.component(engine) if engine else None
        if engine_comp is not None and engine_comp.exec:
            protected.add(engine_comp.exec.split()[0])
        protected.discard(active_bin)

        for comp_id, binary in bars.items():
            if comp_id == active or binary in protected:
                continue
            _kill_process(binary)

        if not active_bin:
            return
        _kill_process(active_bin)
        comp = self.catalog.component(active)
        if comp is None or not comp.exec:
            return
        time.sleep(_RESTART_SETTLE)
        _spawn(comp.exec)

    def start_missing(self, selected: Iterable[str]) -> list[str]:
        """Starts the selected bar / notification / wallpaper process if not running.

        A rice shuts down the user's bar when it opens its own; after the rice
        was uninstalled the config files did not change, so the settings app
        did not restart them (the bar never came back). Only called after an
        uninstall: starting the user's bar at install time, before the
        author's bar has opened, would stack the two. Categories an active rice
        brings itself are skipped.
        """
        if not self._session_live():
            return []
        selected = set(selected)
        provided = set(rice_mod.provided_categories(self.home))
        started: list[str] = []
        for cat in self.catalog.categories:
            if cat.id not in ("bar", "notify", "wallpaper") or cat.id in provided:
                continue
            if (cat.id == "wallpaper" and "wallpaperengine" in selected
                    and self.component_installed("wallpaperengine")):
                script = self._wallpaper_script("wallpaperengine.sh")
                if script is not None and not _process_running(_WPENGINE_PROCESS):
                    _spawn(f"{shlex.quote(str(script))} start")
                    started.append("Wallpaper Engine")
                continue
            comp = next((c for c in cat.components if c.id in selected and c.exec), None)
            if comp is None or not self.component_installed(comp.id):
                continue
            if cat.id == "notify" and self._stop_other_notifiers(comp.id):
                time.sleep(_RESTART_SETTLE)
            if _process_running(comp.exec.split()[0]):
                continue
            _spawn(comp.exec)
            started.append(comp.title)
        return started

    def _stop_other_notifiers(self, keep: str) -> bool:
        """Stops running notification servers that are not selected.

        True if something was stopped: the user was running notifications, so
        the selected server should be started in its place.
        """
        category = next((c for c in self.catalog.categories if c.id == "notify"), None)
        stopped = False
        for comp in (category.components if category else []):
            if comp.id == keep or not comp.exec:
                continue
            binary = comp.exec.split()[0]
            if _process_running(binary):
                _kill_process(binary)
                stopped = True
        return stopped

    def _refresh_wallpaper(self, values: dict[str, str]) -> None:
        """Refreshes the selected wallpaper program and stops the others.

        linux-wallpaperengine has no "exec" in the catalog (its command is set
        up by the script generated from the WPENGINE_* settings), so
        _restart_primary never saw it: switching to a profile with Wallpaper
        Engine did not start the scene, and leaving it kept it playing on top of
        hyprpaper. Two wallpaper programs at once both draw on the background
        layer and which one shows is undefined, so the unselected ones are stopped.
        """
        daemon = values.get("WALLPAPER_DAEMON", "")
        previous = self._last_primaries.get("wallpaper")
        stopped = False
        category = next((c for c in self.catalog.categories if c.id == "wallpaper"), None)
        for comp in (category.components if category else []):
            if comp.id == daemon or not comp.exec:
                continue
            binary = comp.exec.split()[0]
            if _process_running(binary):
                _kill_process(binary)
                stopped = True
        if daemon != "wallpaperengine" and _process_running(_WPENGINE_PROCESS):
            _run(["pkill", "-x", _WPENGINE_PROCESS])
            stopped = True
        if daemon == "wallpaperengine":
            script = self._wallpaper_script("wallpaperengine.sh")
            from . import wpengine
            per_screen = wpengine.parse_per_screen(values.get("WPENGINE_PER_SCREEN", ""))
            main_id = (values.get("WPENGINE_ID") or "").strip()
            if script is not None and (main_id or per_screen):
                # If the profile has an edit recipe for this scene (wpedit.py,
                # e.g. st-gozcu) the copy is prepared first; the script plays it
                # instead of the Workshop original. Without (or failing) a recipe
                # the original plays.
                from . import wpedit
                for ident in dict.fromkeys([main_id, *per_screen.values()]):
                    if ident:
                        wpedit.ensure(ident)
                # The script first stops the running copy, then reads the
                # monitors from hyprctl and puts the scene on each one.
                _spawn(f"{shlex.quote(str(script))} start")
            return
        if daemon == "swww":
            script = self._wallpaper_script("wallpaper.sh")
            image = self.wallpaper_file(values)
            if script is not None and image.is_file():
                if not _run([str(script), "set", str(image)]):
                    raise RuntimeError(f"Could not apply {image} with awww/swww")
                return
        self._restart_primary(daemon, always=stopped or (
            previous is not None and previous != daemon))

    def _restart_primary(self, comp_id: str, always: bool) -> None:
        """Notification/wallpaper daemon: refreshed only if ALREADY running.

        Unlike the bar, the "don't touch it if it's not running" rule applies
        here: the user may have stopped the notification daemon on purpose,
        and moving a slider must not bring it back.
        """
        comp = self.catalog.component(comp_id) if comp_id else None
        if comp is None or not comp.exec:
            return
        binary = comp.exec.split()[0]
        if not always and not _process_running(binary):
            return
        _kill_process(binary)
        time.sleep(_RESTART_SETTLE)
        _spawn(comp.exec)

    # --- theme ------------------------------------------------------------
    def _apply_gsettings(self, values: dict[str, str],
                         selected: list[str]) -> None:
        """modules/theme.sh:hook_gtk_theme + theme_apply_color_scheme."""
        if shutil.which("gsettings") is None:
            return
        light = values.get("COLOR_SCHEME", "dark") == "light"
        schema = "org.gnome.desktop.interface"

        gtk_theme = values.get("GTK_THEME_NAME") or (
            "Adwaita" if light else "Adwaita-dark")
        icon_theme = values.get("ICON_THEME_NAME")
        if not icon_theme:
            if "icon-theme" in selected:
                icon_theme = "Papirus-Light" if light else "Papirus-Dark"
            else:
                icon_theme = "Adwaita"

        pairs = [
            ("color-scheme", "prefer-light" if light else "prefer-dark"),
            ("gtk-theme", gtk_theme),
            ("icon-theme", icon_theme),
            ("cursor-theme", values.get("CURSOR_THEME", "")),
            ("cursor-size", values.get("CURSOR_SIZE", "")),
            ("font-name", f"{values.get('FONT_FAMILY', '')} "
                          f"{values.get('FONT_SIZE', '')}".strip()),
        ]
        for key, value in pairs:
            if value:
                _run(["gsettings", "set", schema, key, str(value)])

    def _apply_cursor(self, values: dict[str, str]) -> None:
        """modules/theme.sh:hook_cursor_theme."""
        theme = values.get("CURSOR_THEME", "")
        size = values.get("CURSOR_SIZE", "")
        if not theme:
            return
        # Cursors shipped with the repo (assets/cursors, e.g. Gozcu's Gozcu-Cursors)
        # are not installed by a package: they are copied to the user's icons directory.
        bundled = self.root / "assets" / "cursors" / theme
        if bundled.is_dir():
            target = Path.home() / ".local/share/icons" / theme
            shutil.rmtree(target, ignore_errors=True)
            shutil.copytree(bundled, target, symlinks=True)
        directory = Path.home() / ".icons" / "default"
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "index.theme").write_text(
            f"[Icon Theme]\nName={theme}\nInherits={theme}\n", encoding="utf-8")
        if size:
            self._hyprctl("setcursor", theme, str(size))
        # Flatpak apps see the theme under /run/host/... but since XCURSOR_PATH
        # is empty they do not look there and fall back to the default arrow
        # (see modules/theme.sh:theme_flatpak_cursor_path).
        _run(["flatpak", "override", "--user",
              "--env=XCURSOR_PATH=/run/host/user-share/icons:/run/host/share/icons"])

    def _apply_firefox_theme(self) -> None:
        """Copies the generated userChrome.css into every Firefox profile.

        Firefox does not read userChrome.css from ~/.config: it wants it in each
        profile's own ``chrome/`` directory, and since Firefox 69 only reads the
        file when ``toolkit.legacyUserProfileCustomizations.stylesheets`` is
        on. install.sh did this with modules/desktop.sh:install_firefox_theme;
        the app side had no counterpart, so people changing the theme from the
        settings app kept Firefox in the old colors.
        """
        source = self.config_home / "hyprsetup/firefox/userChrome.css"
        if not source.is_file():
            return
        pref = ('\n// hyprsetup: read userChrome.css\n'
                'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);\n')
        for directory in firefox_profile_dirs(self.home, self.config_home):
            try:
                chrome = directory / "chrome"
                chrome.mkdir(parents=True, exist_ok=True)
                target = chrome / "userChrome.css"
                if not target.is_file() or target.read_bytes() != source.read_bytes():
                    self._backup(target)
                    shutil.copyfile(source, target)
                user_js = directory / "user.js"
                current = user_js.read_text(errors="ignore") if user_js.is_file() else ""
                if "legacyUserProfileCustomizations" not in current:
                    with user_js.open("a", encoding="utf-8") as handle:
                        handle.write(pref)
            except OSError:
                continue                # if one profile cannot be written, keep going

    def _install_kde_color_scheme(self) -> None:
        """lib/render.sh:install_kde_color_scheme + _sync_kdedefaults.

        Colors embedded in kdeglobals are not enough on their own: Breeze reads
        the active palette from the .colors file pointed to by [General]
        ColorScheme=<name>. Also ~/.config/kdedefaults/kdeglobals comes FIRST
        in the KConfig cascade and its ColorScheme silently overrides ours.
        """
        kdeglobals = self.config_home / "kdeglobals"
        if not kdeglobals.is_file():
            return
        scheme = ""
        for line in kdeglobals.read_text(encoding="utf-8",
                                         errors="replace").splitlines():
            if line.startswith("ColorScheme="):
                scheme = line.split("=", 1)[1].strip()
                break
        if not scheme:
            return

        dest_dir = Path.home() / ".local/share/color-schemes"
        dest_dir.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(kdeglobals, dest_dir / f"{scheme}.colors")

        kdedefaults = self.config_home / "kdedefaults" / "kdeglobals"
        if not kdedefaults.is_file():
            return
        if shutil.which("kwriteconfig6"):
            _run(["kwriteconfig6", "--file", str(kdedefaults),
                  "--group", "General", "--key", "ColorScheme", scheme])
            _run(["kwriteconfig6", "--file", str(kdedefaults),
                  "--group", "KDE", "--key", "widgetStyle", "Breeze"])
            return
        self._backup(kdedefaults)
        text = kdedefaults.read_text(encoding="utf-8", errors="replace")
        lines = text.splitlines()
        if not any(line.startswith("[General]") for line in lines):
            lines.append("[General]")
        for index, line in enumerate(lines):
            if line.startswith("ColorScheme="):
                lines[index] = f"ColorScheme={scheme}"
                break
        else:
            lines.insert(lines.index("[General]") + 1, f"ColorScheme={scheme}")
        kdedefaults.write_text("\n".join(lines) + "\n", encoding="utf-8")

    @staticmethod
    def _restart_open_kde_qt_apps() -> None:
        """modules/theme.sh:_restart_open_kde_qt_apps.

        We do not send KDE's live-theme D-Bus signal; an open Dolphin/ark/
        gwenview only sees the new colors after a restart. All three use the
        kdeglobals palette only when QT_QPA_PLATFORMTHEME=kde.
        """
        running = [app for app in ("dolphin", "ark", "gwenview")
                   if _process_running(app)]
        if not running:
            return
        for app in running:
            _run(["pkill", "-x", app])
        time.sleep(_RESTART_SETTLE)
        for app in running:
            _spawn(app, env={"QT_QPA_PLATFORMTHEME": "kde"})


