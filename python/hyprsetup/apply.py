def firefox_profile_dirs(home: Path, config_home: Path) -> list[Path]:
    """Firefox profile directories listed in profiles.ini.

    Firefox 147+ keeps NEW profiles under $XDG_CONFIG_HOME/mozilla/firefox;
    older installs (and upgraded ones) stay in ~/.mozilla/firefox. Both are
    read: looking only at ~/.mozilla left fresh installs without the theme.
    Relative Path= entries are relative to the profiles.ini directory.
    """
    found: list[Path] = []
    for base in (home / ".mozilla/firefox", config_home / "mozilla/firefox"):
        try:
            text = (base / "profiles.ini").read_text(errors="ignore")
        except OSError:
            continue                    # Firefox never opened here: no profile
        for line in text.splitlines():
            if not line.startswith("Path="):
                continue
            raw = line.split("=", 1)[1].strip()
            directory = Path(raw) if raw.startswith("/") else base / raw
            if directory.is_dir() and directory not in found:
                found.append(directory)
    return found


def _busctl_strings(*argv: str) -> list[str]:
    """Turns the "as N \"a\" \"b\"" array in ``busctl --user`` output into a list."""
    try:
        text = subprocess.run(["busctl", "--user", *argv], capture_output=True,
                              text=True, timeout=5, check=False).stdout
        words = shlex.split(text)
    except (OSError, subprocess.SubprocessError, ValueError):
        return []
    return words[2:] if len(words) >= 2 and words[0] in ("as", "s") else words[1:]


def _reregister_tray_items() -> None:
    """Re-registers icons that disappeared from the tray (like Proton VPN).

    When the bar restarts, or another process (kded6, which comes with
    Dolphin) takes over the StatusNotifierWatcher name, items must
    re-register with the new watcher. Chromium/nm-applet/Steam do this
    themselves; Proton VPN (flatpak, 4.x) does not and dropped out of the
    tray while still alive on D-Bus. Unregistered "*StatusNotifierItem*"
    names are reported to the watcher; if the name's owner is already
    registered (by its unique name) it is skipped — so the same icon does
    not appear twice.
    """
    if shutil.which("busctl") is None:
        return
    registered = _busctl_strings(
        "get-property", "org.kde.StatusNotifierWatcher", "/StatusNotifierWatcher",
        "org.kde.StatusNotifierWatcher", "RegisteredStatusNotifierItems")
    owners = {item.split("/", 1)[0] for item in registered}
    names = _busctl_strings("call", "org.freedesktop.DBus", "/org/freedesktop/DBus",
                            "org.freedesktop.DBus", "ListNames")
    for name in names:
        if "StatusNotifierItem" not in name or name in owners:
            continue
        owner = _busctl_strings("call", "org.freedesktop.DBus", "/org/freedesktop/DBus",
                                "org.freedesktop.DBus", "GetNameOwner", "s", name)
        if owner and owner[0] in owners:
            continue
        _run(["busctl", "--user", "call", "org.kde.StatusNotifierWatcher",
              "/StatusNotifierWatcher", "org.kde.StatusNotifierWatcher",
              "RegisterStatusNotifierItem", "s", name])


def _reregister_tray_items_later(delay: float = 3.0) -> None:
    """Waits until the bar has set up the watcher/host, then repairs the tray."""
    def work() -> None:
        time.sleep(delay)
        _reregister_tray_items()
    threading.Thread(target=work, daemon=True).start()


# ------------------------------------------------------- process helpers --
def _timer_enabled(unit: str) -> bool:
    """Is the systemd user timer enabled?"""
    try:
        out = subprocess.run(["systemctl", "--user", "is-enabled", unit],
                             capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return False
    return out.stdout.strip() == "enabled"


def _run(argv: list[str]) -> bool:
    """Runs the command quietly; returns whether it succeeded."""
    if shutil.which(argv[0]) is None:
        return False
    try:
        return subprocess.run(argv, capture_output=True, timeout=30,
                              check=False).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def _read_pacman_local_db(db_dir: Path = Path("/var/lib/pacman/local")) -> set[str]:
    """Read installed package names + ``Provides`` directly from pacman's local DB.

    Produces the exact same set as ``LC_ALL=C pacman -Qi`` (~6× faster because it
    avoids spawning pacman and formatting every metadata field). Returns an empty
    set if the DB does not exist so the caller can fall back to ``pacman -Qi``.
    """
    if not db_dir.is_dir():
        return set()
    names: set[str] = set()
    try:
        entries = list(db_dir.iterdir())
    except OSError:
        return set()
    for entry in entries:
        desc = entry / "desc"
        try:
            text = desc.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        section = ""
        for line in text.splitlines():
            if line.startswith("%") and line.endswith("%"):
                section = line
            elif not line:
                section = ""
            elif section == "%NAME%":
                names.add(line.strip())
            elif section == "%PROVIDES%":
                item = line.strip()
                if item:
                    names.add(re.split(r"[<>=]", item, maxsplit=1)[0])
    return names


def _parse_installed(text: str) -> set[str]:
    """Name + provides set from ``LC_ALL=C pacman -Qi`` output.

    Provides values may carry a version constraint ("libva-mesa-driver=1:26")
    and long lists are split over indented continuation lines.
    """
    names: set[str] = set()
    field = ""
    for line in text.splitlines():
        if line and not line[0].isspace():
            key, sep, value = line.partition(":")
            field = key.strip() if sep else ""
        else:
            value = line
        if field == "Name":
            names.add(value.strip())
        elif field == "Provides":
            for item in value.split():
                if item != "None":
                    names.add(re.split(r"[<>=]", item, maxsplit=1)[0])
    return names


def _output(argv: list[str]) -> str:
    """The command's standard output; an empty string if it fails."""
    if shutil.which(argv[0]) is None:
        return ""
    try:
        return subprocess.run(argv, capture_output=True, text=True, timeout=30,
                              check=False).stdout
    except (OSError, subprocess.SubprocessError):
        return ""


#: linux-wallpaperengine's process name in the kernel (truncated to 15
#: characters; pgrep/pkill -x do not match the full name).
_WPENGINE_PROCESS = "linux-wallpaper"


def _process_running(name: str) -> bool:
    return _run(["pgrep", "-x", name])


def _kill_process(binary: str) -> None:
    """Kills the process and its wrapper.

    Some backends (hyprpanel) hand the real work to a ``<name>-app`` wrapper
    and a gjs process it starts. That gjs process is not a DIRECT child of
    the wrapper (PPID=1, i.e. reparented) — ``pkill -P`` never finds it and
    it stays hanging on screen even after the wrapper is killed. To be
    independent of the random hash prefix, ``ags.js`` is searched for in the
    full command line.
    """
    for name in (binary, f"{binary}-app"):
        if not _process_running(name):
            continue
        _run(["pkill", "-P", name])
        _run(["pkill", "-x", name])
    if binary == "hyprpanel":
        _run(["pkill", "-f", r"ags\.js"])


def _spawn(command: str, env: dict[str, str] | None = None) -> None:
    """Starts the command in the background, detached from the session (like setsid -f)."""
    environ = dict(os.environ)
    if env:
        environ.update(env)
    try:
        subprocess.Popen(command, shell=True, env=environ,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         stdin=subprocess.DEVNULL, start_new_session=True)
    except (OSError, ValueError):
        pass
