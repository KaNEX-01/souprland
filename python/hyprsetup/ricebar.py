"""Adjusting a profile's own bar from the settings app.

A profile (rice.py) brings its own bar: waybar, Quickshell, eww or skadi. This
project's Status Bar settings (BAR_*) generate its own templates; under an active
profile they were never used and the bar could not be adjusted. Here:

* ``detect`` — derives the bar's kind, files and adjustable fields from the
  ``[bar]`` table in the active profile's manifest.
* Waybar fields are built in (the format is the same in every theme): position,
  height, margins, module spacing, font family/size, opacity, corners and module
  visibility. ``config.jsonc`` is updated in place, preserving comments and trailing
  commas; style goes into a marked block at the end of ``style.css`` (the later
  rule wins). Waybar reloads on SIGUSR2.
* For other kinds (Quickshell/skadi) the fields are defined in the manifest by
  paths into the author's JSON settings file.

Values are kept per theme in ``~/.config/hyprsetup/rice-adjust/<profile>.json``
and reapplied after every install: switching themes and coming back does not lose
the adjustments.

In a mix (mix.py), if a profile's bar is chosen for the bar slot, the same
``[bar]`` table is used: the part installs the author's files in the same places.
"""

from __future__ import annotations

import json
import re
import shlex
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import rice as rice_mod

CSS_BEGIN = "/* hyprsetup: begin — generated by the settings app, do not edit by hand */"
CSS_END = "/* hyprsetup: end */"
#: Legacy Turkish markers from pre-English installs; still recognized when reading
#: and replaced with the English ones on the next write.
_LEGACY_CSS_BEGIN = "/* hyprsetup: başlangıç — ayar uygulaması üretir, elle düzenlemeyin */"
_LEGACY_CSS_END = "/* hyprsetup: son */"
_CSS_BEGIN_RE = "(?:" + re.escape(CSS_BEGIN) + "|" + re.escape(_LEGACY_CSS_BEGIN) + ")"
_CSS_END_RE = "(?:" + re.escape(CSS_END) + "|" + re.escape(_LEGACY_CSS_END) + ")"


@dataclass
class Field:
    key: str
    title: str
    type: str                       # choice | int | bool | text | modules
    path: str = ""                  # JSON path ("bar.position", "windows.0.height")
    choices: list[str] = field(default_factory=list)
    minimum: int = 0
    maximum: int = 100
    unit: str = ""
    subtitle: str = ""


@dataclass
class Bar:
    profile: str
    kind: str                       # waybar | quickshell | eww | skadi
    label: str
    config: Path | None = None      # waybar config / JSON settings file
    style: Path | None = None       # waybar style.css
    reload: str = ""                # non-waybar: command to run on change
    fields: list[Field] = field(default_factory=list)
    note: str = ""
    source: str = "rice"            # rice | mix (bar is part of a mix)


#: Waybar's built-in fields; paths are "json:" (config) or "css:" (style).
WAYBAR_FIELDS = [
    Field("position", "Position", "choice", "json:position",
          choices=["top", "bottom", "left", "right"]),
    Field("height", "Height", "int", "json:height", minimum=0, maximum=80, unit="px",
          subtitle="0 = fit content"),
    Field("margin-top", "Top margin", "int", "margin:0", minimum=0, maximum=60, unit="px"),
    Field("margin-side", "Side margins", "int", "margin:1", minimum=0, maximum=400, unit="px"),
    Field("margin-bottom", "Bottom margin", "int", "margin:2", minimum=0, maximum=60, unit="px"),
    Field("spacing", "Module spacing", "int", "json:spacing", minimum=0, maximum=30,
          unit="px"),
    Field("font-size", "Font size", "int", "css:font-size", minimum=0, maximum=30, unit="px",
          subtitle="0 = author's"),
    Field("font-family", "Font", "text", "css:font-family", subtitle="empty = author's"),
    Field("opacity", "Opacity", "int", "css:opacity", minimum=20, maximum=100, unit="%"),
    Field("radius", "Corner rounding", "int", "css:radius", minimum=-1, maximum=30,
          unit="px", subtitle="-1 = author's"),
    Field("modules", "Visible modules", "modules", "json:modules"),
]


# ----------------------------------------------------------------- detection ---
def detect(root: Path, home: Path | None = None) -> Bar | None:
    """The active profile's bar (None if absent or not defined in the manifest)."""
    home = rice_mod._home(home)
    state = rice_mod.read_state(home)
    profile = state.get("profile", "")
    source = "rice"
    if not profile:
        profile, source = _mix_bar_profile(home), "mix"
    if not profile or not rice_mod.is_rice(root, profile):
        return None
    spec = _bar_spec(root, profile)
    if not spec:
        return None
    kind = spec.get("kind", "")
    bar = Bar(profile=profile, kind=kind, label=spec.get("label", kind),
              reload=spec.get("reload", ""), note=spec.get("note", ""), source=source)
    if spec.get("config"):
        bar.config = _resolve(rice_mod.expand(spec["config"], home))
    if spec.get("style"):
        bar.style = _resolve(rice_mod.expand(spec["style"], home))
    if source == "mix":
        # If the part did not install the bar's file (e.g. only its launcher was
        # chosen), there is nothing to adjust.
        raw = spec.get("config") or spec.get("style") or ""
        owned = [Path(p) for p in _mix_installed(home).get("owned", [])]
        if not raw or not rice_mod.is_owned(rice_mod.expand(raw, home), owned):
            return None
    if kind == "waybar":
        bar.fields = list(WAYBAR_FIELDS)
    for raw in spec.get("field", []):
        bar.fields.append(Field(
            key=raw["key"], title=raw.get("title", raw["key"]), type=raw.get("type", "text"),
            path=raw.get("path", ""), choices=list(raw.get("choices", [])),
            minimum=int(raw.get("min", 0)), maximum=int(raw.get("max", 100)),
            unit=raw.get("unit", ""), subtitle=raw.get("subtitle", "")))
    return bar


def _mix_installed(home: Path) -> dict:
    from . import mix as mix_mod
    return mix_mod.read_state(home).get("installed") or {}


def _mix_bar_profile(home: Path) -> str:
    """Profile of the mix's bar part ("" = bar slot empty)."""
    ref = (_mix_installed(home).get("parts") or {}).get("bar", "")
    return ref.split("/", 1)[0] if ref else ""


def _bar_spec(root: Path, profile: str) -> dict:
    import tomllib
    data = tomllib.loads(rice_mod.manifest_path(root, profile).read_text(encoding="utf-8"))
    return data.get("bar", {})


def _resolve(path: Path) -> Path:
    """Follows symlinks (ad1822: config.jsonc → config_old.jsonc)."""
    try:
        return path.resolve() if path.exists() else path
    except OSError:
        return path


# -------------------------------------------------------------- JSONC scanner ---
def _skip(text: str, i: int) -> int:
    """Skips whitespace and comments."""
    n = len(text)
    while i < n:
        if text[i].isspace():
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j + 1
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        else:
            break
    return i


def _string_end(text: str, i: int) -> int:
    i += 1
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == '"':
            return i + 1
        i += 1
    return i


def _value_end(text: str, i: int) -> int:
    """End position of the JSON value starting at ``i`` (comments/strings skipped)."""
    if text[i] == '"':
        return _string_end(text, i)
    if text[i] in "[{":
        depth = 0
        while i < len(text):
            i = _skip(text, i)
            ch = text[i]
            if ch == '"':
                i = _string_end(text, i)
                continue
            if ch in "[{":
                depth += 1
            elif ch in "]}":
                depth -= 1
                if depth == 0:
                    return i + 1
            i += 1
        return i
    match = re.compile(r"[^,}\]\s/]+").match(text, i)
    return match.end() if match else i


def _top_level(text: str) -> dict[str, tuple[int, int]]:
    """Key → value span (start, end) in the root object."""
    out: dict[str, tuple[int, int]] = {}
    i = _skip(text, 0)
    if i >= len(text) or text[i] != "{":
        return out
    i += 1
    while i < len(text):
        i = _skip(text, i)
        if i >= len(text) or text[i] == "}":
            break
        if text[i] == ",":
            i += 1
            continue
        if text[i] != '"':
            i += 1
            continue
        end = _string_end(text, i)
        key = json.loads(text[i:end])
        i = _skip(text, end)
        if i < len(text) and text[i] == ":":
            i = _skip(text, i + 1)
            vend = _value_end(text, i)
            out[key] = (i, vend)
            i = vend
    return out


def _loads_lenient(text: str):
    """JSON with comments and trailing commas (JSONC) → Python."""
    out, i = [], 0
    while i < len(text):
        if text[i] == '"':
            end = _string_end(text, i)
            out.append(text[i:end])
            i = end
        elif text.startswith("//", i) or text.startswith("/*", i):
            i = _skip(text, i)
            out.append(" ")
        else:
            out.append(text[i])
            i += 1
    cleaned = re.sub(r",(\s*[}\]])", r"\1", "".join(out))
    return json.loads(cleaned)


def jsonc_get(text: str, key: str):
    span = _top_level(text).get(key)
    if span is None:
        return None
    return _loads_lenient(text[span[0]:span[1]])


def jsonc_set(text: str, key: str, value) -> str:
    """Updates a root key in place (adds it if missing); leaves the rest untouched."""
    rendered = json.dumps(value, ensure_ascii=False)
    spans = _top_level(text)
    if key in spans:
        start, end = spans[key]
        return text[:start] + rendered + text[end:]
    brace = text.index("{", _skip(text, 0))
    return text[:brace + 1] + f"\n  {json.dumps(key)}: {rendered}," + text[brace + 1:]


def jsonc_delete(text: str, key: str) -> str:
    spans = _top_level(text)
    if key not in spans:
        return text
    start, end = spans[key]
    key_start = text.rfind(json.dumps(key), 0, start)
    after = _skip(text, end)
    if after < len(text) and text[after] == ",":
        end = after + 1
    return text[:key_start] + text[end:]


# ------------------------------------------------------------------- waybar ---
_MODULE_KEYS = ("modules-left", "modules-center", "modules-right")


def _margins(text: str) -> list[int]:
    """[top, side, bottom] — the "margin" shorthand or the margin-* keys."""
    def px(v) -> int:
        try:
            return int(float(str(v).replace("px", "").strip() or 0))
        except ValueError:
            return 0
    short = jsonc_get(text, "margin")
    if isinstance(short, str) and short.strip():
        # CSS shorthand: 1 value → all; 2 → vertical horizontal; 3 → top horizontal
        # bottom; 4 → top right bottom left.
        p = [px(v) for v in short.split()][:4]
        top, side, bottom = {1: (p[0], p[0], p[0]), 2: (p[0], p[1], p[0]),
                             3: (p[0], p[1], p[2]), 4: (p[0], p[3], p[2])}[len(p)]
        return [top, side, bottom]
    if isinstance(short, (int, float)):
        return [int(short)] * 3
    return [px(jsonc_get(text, "margin-top") or 0),
            px(jsonc_get(text, "margin-left") or 0),
            px(jsonc_get(text, "margin-bottom") or 0)]


def _css_block(css: str) -> dict[str, str]:
    match = re.search(_CSS_BEGIN_RE + r"(.*?)" + _CSS_END_RE, css, re.S)
    out: dict[str, str] = {}
    if not match:
        return out
    for key in ("font-size", "font-family", "opacity", "radius"):
        found = re.search(rf"/\* {key}=(.*?) \*/", match.group(1))
        if found:
            out[key] = found.group(1)
    return out


def _render_css(values: dict) -> str:
    lines = [CSS_BEGIN]
    inner, win = [], []
    if int(values.get("font-size") or 0) > 0:
        inner.append(f"font-size: {int(values['font-size'])}px;")
        lines.append(f"/* font-size={int(values['font-size'])} */")
    family = (values.get("font-family") or "").strip()
    if family:
        inner.append(f'font-family: "{family}";')
        lines.append(f"/* font-family={family} */")
    opacity = int(values.get("opacity") or 100)
    if opacity < 100:
        win.append(f"opacity: {opacity / 100:.2f};")
        lines.append(f"/* opacity={opacity} */")
    radius = int(values.get("radius", -1) if values.get("radius") not in (None, "") else -1)
    if radius >= 0:
        win.append(f"border-radius: {radius}px;")
        lines.append(f"/* radius={radius} */")
    if inner:
        # window#waybar * (id + element) is more specific than the author's rules
        # like #clock: the size reaches every module.
        lines.append("window#waybar, window#waybar * { " + " ".join(inner) + " }")
    if win:
        lines.append("window#waybar { " + " ".join(win) + " }")
    lines.append(CSS_END)
    return "\n".join(lines)


def _waybar_read(bar: Bar) -> dict:
    text = bar.config.read_text(encoding="utf-8") if bar.config and bar.config.is_file() else "{}"
    margins = _margins(text)
    css = bar.style.read_text(encoding="utf-8") if bar.style and bar.style.is_file() else ""
    block = _css_block(css)
    return {
        "position": jsonc_get(text, "position") or "top",
        "height": int(jsonc_get(text, "height") or 0),
        "margin-top": margins[0], "margin-side": margins[1], "margin-bottom": margins[2],
        "spacing": int(jsonc_get(text, "spacing") or 0),
        "font-size": int(block.get("font-size", 0) or 0),
        "font-family": block.get("font-family", ""),
        "opacity": int(block.get("opacity", 100) or 100),
        "radius": int(block.get("radius", -1)),
        "modules": {k: list(jsonc_get(text, k) or []) for k in _MODULE_KEYS},
    }


def _waybar_write(bar: Bar, values: dict, original_modules: dict | None) -> None:
    if bar.config and bar.config.is_file():
        text = bar.config.read_text(encoding="utf-8")
        for key in ("position", "spacing"):
            if key in values:
                text = jsonc_set(text, key, values[key])
        if "height" in values:
            text = (jsonc_set(text, "height", int(values["height"])) if int(values["height"])
                    else jsonc_delete(text, "height"))
        if any(k in values for k in ("margin-top", "margin-side", "margin-bottom")):
            top, side, bottom = _margins(text)
            top = int(values.get("margin-top", top))
            side = int(values.get("margin-side", side))
            bottom = int(values.get("margin-bottom", bottom))
            if jsonc_get(text, "margin") is not None:
                text = jsonc_set(text, "margin", f"{top}px {side}px {bottom}px {side}px")
            else:
                for key, value in (("margin-top", top), ("margin-left", side),
                                   ("margin-right", side), ("margin-bottom", bottom)):
                    text = jsonc_set(text, key, value)
        if "modules" in values and original_modules:
            hidden = set(values["modules"].get("hidden", []))
            for key in _MODULE_KEYS:
                if key in original_modules:
                    text = jsonc_set(text, key,
                                     [m for m in original_modules[key] if m not in hidden])
        bar.config.write_text(text, encoding="utf-8")
    if bar.style and bar.style.is_file():
        css = bar.style.read_text(encoding="utf-8")
        css = re.sub(r"\n?" + _CSS_BEGIN_RE + r".*?" + _CSS_END_RE + r"\n?",
                     "\n", css, flags=re.S).rstrip("\n")
        block = _render_css({**_css_block(bar.style.read_text(encoding="utf-8")),
                             **{k: v for k, v in values.items()
                                if k in ("font-size", "font-family", "opacity", "radius")}})
        if block.count("\n") > 1:
            css += "\n\n" + block
        bar.style.write_text(css + "\n", encoding="utf-8")


# ---------------------------------------------------------------- JSON file ---
def _json_path_get(data, path: str):
    for part in path.split("."):
        if isinstance(data, list):
            data = data[int(part)] if part.isdigit() and int(part) < len(data) else None
        elif isinstance(data, dict):
            data = data.get(part)
        else:
            return None
        if data is None:
            return None
    return data


def _json_path_set(data, path: str, value) -> None:
    parts = path.split(".")
    for part in parts[:-1]:
        data = data[int(part)] if isinstance(data, list) else data.setdefault(part, {})
    last = parts[-1]
    if isinstance(data, list):
        data[int(last)] = value
    else:
        data[last] = value


def _json_read(bar: Bar) -> dict:
    if not bar.config or not bar.config.is_file():
        return {}
    data = _loads_lenient(bar.config.read_text(encoding="utf-8"))
    return {f.key: _json_path_get(data, f.path) for f in bar.fields}


def _json_write(bar: Bar, values: dict) -> None:
    if not bar.config or not bar.config.is_file():
        return
    data = _loads_lenient(bar.config.read_text(encoding="utf-8"))
    by_key = {f.key: f for f in bar.fields}
    for key, value in values.items():
        if key in by_key and by_key[key].path:
            _json_path_set(data, by_key[key].path, value)
    bar.config.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# --------------------------------------------------------------- public API ---
def adjust_path(profile: str, home: Path | None = None) -> Path:
    return rice_mod._home(home) / ".config/hyprsetup/rice-adjust" / f"{profile}.json"


def _saved(profile: str, home: Path | None = None) -> dict:
    try:
        return json.loads(adjust_path(profile, home).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def read(bar: Bar, home: Path | None = None) -> dict:
    """The bar's current values (field key → value)."""
    if bar.kind == "waybar":
        values = _waybar_read(bar)
        saved = _saved(bar.profile, home)
        original = saved.get("original_modules") or values["modules"]
        values["modules"] = {"all": original,
                             "hidden": saved.get("values", {}).get("modules", {}).get("hidden", [])}
        return values
    return _json_read(bar)


def write(bar: Bar, changes: dict, home: Path | None = None, reload: bool = True) -> None:
    """Writes changes to the bar's files, saves them per theme, and reloads."""
    saved = _saved(bar.profile, home)
    if bar.kind == "waybar" and "original_modules" not in saved:
        # Modules are hidden by removing them from the list; the original list is
        # kept so they can be restored (the author's order is preserved).
        text = bar.config.read_text(encoding="utf-8") if bar.config else "{}"
        saved["original_modules"] = {k: list(jsonc_get(text, k) or []) for k in _MODULE_KEYS}
    # The author's value is saved before the first change, so "revert to the
    # author's values" can write it back right away without reinstalling files.
    author = saved.setdefault("author", {})
    if any(k not in author for k in changes):
        current = read(bar, home)
        for key in changes:
            if key not in author:
                author[key] = {"hidden": []} if key == "modules" else current.get(key)
    saved.setdefault("values", {}).update(changes)
    path = adjust_path(bar.profile, home)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(saved, indent=2, ensure_ascii=False), encoding="utf-8")
    _apply(bar, changes, saved)
    if reload:
        _reload(bar)


def _apply(bar: Bar, values: dict, saved: dict) -> None:
    if bar.kind == "waybar":
        _waybar_write(bar, values, saved.get("original_modules"))
    else:
        _json_write(bar, {k: v for k, v in values.items() if v is not None})


def reset(bar: Bar, home: Path | None = None, reload: bool = True) -> None:
    """Writes back the author's values and deletes the per-theme record."""
    saved = _saved(bar.profile, home)
    if saved.get("author"):
        _apply(bar, saved["author"], saved)
        if reload:
            _reload(bar)
    adjust_path(bar.profile, home).unlink(missing_ok=True)


def reapply(root: Path, home: Path | None = None) -> bool:
    """Rewrites the saved adjustments after an install (without reloading)."""
    bar = detect(root, home)
    if bar is None:
        return False
    saved = _saved(bar.profile, home)
    if not saved.get("values"):
        return False
    _apply(bar, saved["values"], saved)
    return True


def _reload(bar: Bar) -> None:
    if bar.kind == "waybar":
        subprocess.run(["pkill", "-SIGUSR2", "-x", "waybar"], capture_output=True)
    elif bar.reload:
        subprocess.Popen(rice_mod._in_slice(bar.reload), start_new_session=True,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def describe(bar: Bar) -> str:
    return f"{bar.label} ({bar.kind}) · {shlex.quote(str(bar.config or '-'))}"
