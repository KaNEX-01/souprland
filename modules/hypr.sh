hook_hyprlock() {
    root_ops_allowed || { debug "PAM step skipped (--configs-only)"; return 0; }
    # hyprlock needs a PAM config for password verification.
    if [[ ! -f /etc/pam.d/hyprlock ]]; then
        warn "/etc/pam.d/hyprlock missing — the lock screen may not be able to verify the password."
        if confirm "Create the default PAM rule (auth include system-auth)?" y; then
            run sudo install -Dm644 /dev/stdin /etc/pam.d/hyprlock <<<"auth include system-auth" \
                || warn "Could not write the PAM rule."
        fi
    fi
}

# ---------------------------------------------------------------- plugins --
# hyprpm plugins are NOT pacman packages: they are built from source against
# the installed Hyprland's header files. This has two consequences and both
# must be told to the user:
#
#   1. Plugins MUST BE REBUILT every time Hyprland is updated
#      ("hyprpm update"). Otherwise Hyprland refuses to load the plugins
#      and silently starts without them — an hy3 user loses the layout engine,
#      a hyprbars user loses the window titles.
#   2. The build may fail (header mismatch, missing base-devel).
#      In that case the install is NOT STOPPED; the plugin is skipped with a warning.
#
# So plugins are not a default in any profile; the user selects them
# explicitly from the TUI or with --only.

_hyprpm_ready() {
    have hyprpm || { warn "hyprpm not found (it comes with the hyprland package) — could not install the plugin."; return 1; }
    # Without build tools hyprpm fails not silently but in an ugly way.
    local missing=()
    have cmake || missing+=(cmake)
    have meson || missing+=(meson)
    have cpio  || missing+=(cpio)
    have git   || missing+=(git)
    if ((${#missing[@]})); then
        warn "Missing tools for building plugins: ${missing[*]}"
        warn "To install: sudo pacman -S --needed base-devel cmake meson cpio git"
        return 1
    fi
    return 0
}

# _hyprpm_enable <component-id> — adds the repo and enables the plugin.
_hyprpm_enable() {
    local id="$1" repo name
    repo=$(catalog_field "$id" plugin_repo)
    name=$(catalog_field "$id" plugin_name)
    [[ -n "$repo" && -n "$name" ]] || { warn "$id: plugin info missing (plugin_repo/plugin_name)"; return 0; }

    _hyprpm_ready || return 0

    if [[ "${DRY_RUN:-0}" == 1 ]]; then
        step "[dry-run] hyprpm add $repo && hyprpm enable $name"
        return 0
    fi

    # "hyprpm add" returns an error when called a second time for the same repo;
    # if it is already added that is fine, so the error is swallowed and enable is still tried.
    if ! grep -q -- "$name" <<<"$(hyprpm list 2>/dev/null)"; then
        step "Adding plugin repo: $repo"
        run hyprpm add "$repo" || warn "hyprpm add failed: $repo (it may already be added)"
    fi

    step "Enabling plugin: $name"
    if ! run hyprpm enable "$name"; then
        warn "Could not enable $name — the build may have failed."
        warn "Try manually: hyprpm update && hyprpm enable $name"
        return 0
    fi
    HYPRPM_ENABLED+=("$name")
    return 0
}

