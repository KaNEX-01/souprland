# shellcheck shell=bash
# modules/hypr.sh — post-install steps specific to the Hyprland core
#
# Convention: for <component-id> define hook_<component_id>() (underscores instead
# of dashes). install.sh calls this function automatically if the component is selected.

hook_hyprland() {
    # The Wayland session file comes from the package; warn if it is missing.
    if [[ ! -f /usr/share/wayland-sessions/hyprland.desktop ]]; then
        warn "/usr/share/wayland-sessions/hyprland.desktop not found — the login manager may not list Hyprland."
    fi
    # User script dir
    run mkdir -p "$HOME/.config/hypr/scripts"
    run mkdir -p "$(dirname "$(wallpaper_file)")"

    # Personal settings file: hyprland.conf sources it, and Hyprland errors if
    # the file is missing. Created once, then never touched.
    local custom="$HOME/.config/hypr/custom.conf"
    if [[ ! -e "$custom" ]]; then
        step "Creating the personal settings file: ~/.config/hypr/custom.conf"
        if [[ "${DRY_RUN:-0}" != 1 ]]; then
            cat >"$custom" <<'EOF'
# Your personal Hyprland settings.
# This file is never overwritten by the installer, and since it is read
# at the very end of hyprland.conf it can override the generated settings.
#
# Example:
#   bind = SUPER, G, exec, steam
#   windowrule = workspace 3 silent, class:^(discord)$
EOF
        fi
    fi

    # The Lua equivalent of the same for Lua mode (HYPR_LANG=lua) — hyprland.lua
    # unconditionally calls require("custom") at the very end, so the file is
    # always created here regardless of HYPR_LANG.
    local custom_lua="$HOME/.config/hypr/custom.lua"
    if [[ ! -e "$custom_lua" ]]; then
        step "Creating the personal settings file: ~/.config/hypr/custom.lua"
        if [[ "${DRY_RUN:-0}" != 1 ]]; then
            cat >"$custom_lua" <<'EOF'
-- Your personal Hyprland settings (Lua config mode).
-- This file is never overwritten by the installer, and since it is
-- require()d at the very end of hyprland.lua it can override the generated
-- settings.
--
-- Example:
--   hl.bind("SUPER + G", hl.dsp.exec_cmd("steam"))
EOF
        fi
    fi

    # hyprland.conf now sources monitors.conf and workspaces.conf UNCONDITIONALLY
    # (even with MANAGE_MONITORS=0 / WORKSPACE_MONITOR_MAP="") — so that settings
    # generated by a tool like nwg-displays are actually read.
    # When the script does not generate these files in its own render step (the
    # content is left to another tool, or no settings are defined), we leave an
    # empty placeholder here; otherwise the sourcing hyprland.conf would error
    # when the file is missing. An existing file is not touched.
    local monitors="$HOME/.config/hypr/monitors.conf"
    if [[ ! -e "$monitors" ]]; then
        step "Creating placeholder: ~/.config/hypr/monitors.conf"
        if [[ "${DRY_RUN:-0}" != 1 ]]; then
            printf '# hyprsetup:managed (placeholder) — if a tool like nwg-displays\n# rewrites this file, the script will not touch it again.\nmonitor = , preferred, auto, 1\n' >"$monitors"
        fi
    fi
    local workspaces="$HOME/.config/hypr/workspaces.conf"
    if [[ ! -e "$workspaces" ]]; then
        step "Creating placeholder: ~/.config/hypr/workspaces.conf"
        if [[ "${DRY_RUN:-0}" != 1 ]]; then
            printf '# hyprsetup:managed (placeholder) — no workspace → display mapping\n# (can be filled in with nwg-displays or WORKSPACE_MONITOR_MAP).\n' >"$workspaces"
        fi
    fi
}

