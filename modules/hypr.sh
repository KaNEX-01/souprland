hook_hy3() {
    _hyprpm_enable hy3
    # hy3 is a LAYOUT engine: it replaces dwindle/master. If LAYOUT is still
    # dwindle/master, the plugin loads but is never used — the user is left
    # with "I installed it but nothing changed".
    if [[ "${LAYOUT:-dwindle}" != "hy3" ]]; then
        warn "hy3 installed but LAYOUT=\"$LAYOUT\" — set LAYOUT=\"hy3\" for it to take effect."
        warn "  ./install.sh --reapply --set LAYOUT=hy3"
    fi
}

hook_hypridle() {
    # hypridle is started via exec-once; prefer the systemd unit if there is one.
    if [[ -n "$(systemctl --user list-unit-files --no-legend hypridle.service 2>/dev/null)" ]]; then
        enable_user_service "hypridle.service"
    fi
}

hook_hyprland_extras() {
    # hyprpicker needs no extra step (one-shot command, MOD+SHIFT+C).
    #
    # hyprshade's schedule (hyprshade.toml) does not run by itself: it needs a
    # systemd user timer. It is only set up if NIGHT_SHADER is set — enabling
    # the timer while it is empty leaves an empty unit that applies no shader and
    # the user starts searching "why is it not working".
    have hyprshade || return 0
    if [[ -z "${NIGHT_SHADER:-}" ]]; then
        step "Night light is off (NIGHT_SHADER empty) — hyprshade timer not set up"
        return 0
    fi

    # Using it together with hyprsunset tints the screen twice as yellow; if both
    # are selected the user should be warned (the install is not stopped).
    if in_list "hyprsunset" "${SELECTED[@]}"; then
        warn "Both hyprsunset and NIGHT_SHADER are enabled — the screen may be tinted twice."
        warn "Turn one off: NIGHT_SHADER=\"\" in the settings app, or remove"
        warn "hyprsunset from install.sh's DEFAULT_COMPONENTS list."
    fi

    step "Enabling the hyprshade timer ($NIGHT_SHADER, $NIGHT_SHADER_START–$NIGHT_SHADER_END)"
    run hyprshade install || warn "hyprshade install failed (timer not set up)"
    enable_user_service "hyprshade.timer"
}

# If the wallpaper file is missing, generates a plain-color fallback from the
# theme; so hyprpaper/swww do not error on first start.
#
# This should only kick in when WALLPAPER_IMAGE/WALLPAPER_STYLE are empty (the
# profile specified neither a real image nor a pattern). main() in install.sh
# runs wallpaper_step (the real image/pattern generator) BEFORE these hooks —
# otherwise the generic gradient generated here would make the file "already
# exist" and block the real image/pattern.
_ensure_wallpaper() {
    local path
    path=$(wallpaper_file)
    [[ -f "$path" ]] && return 0
    run mkdir -p "$(dirname "$path")"

    # Take three colors from the theme: center (surface), edge (dark background) and accent.
    local colors surface bg_dark accent
    colors=$(PYTHONPATH="$SETUP_ROOT/python" python3 -c \
        "from hyprsetup import themes
p = themes.THEMES.get('${THEME}', themes.THEMES[themes.DEFAULT])
print(p['SURFACE'], p['BG_DARK'], p['ACCENT'])" 2>/dev/null || echo "313244 11111b 89b4fa")
    read -r surface bg_dark accent <<<"$colors"

    # A subtle radial gradient instead of a plain color: looks much tidier than a
    # single color, and the wallpaper changes when the theme changes.
    local magick_cmd=""
    if have magick; then magick_cmd="magick"; elif have convert; then magick_cmd="convert"; fi

    if [[ -n "$magick_cmd" ]]; then
        step "Generating the default wallpaper (theme gradient): $path"
        if ! run "$magick_cmd" -size 3840x2160 \
                "radial-gradient:#$surface-#$bg_dark" \
                -attenuate 0.35 +noise Gaussian \
                -fill "#$accent" -draw "circle 3400,300 3400,140" \
                -blur 0x60 \
                "$path"; then
            warn "Could not generate the gradient, falling back to a plain color."
            run "$magick_cmd" -size 3840x2160 "xc:#$bg_dark" "$path" \
                || warn "Could not generate the wallpaper."
        fi
    else
        warn "Wallpaper not found: $path"
        warn "Put an image there or change the path in ~/.config/hypr/hyprpaper.conf."
    fi
}

# Wallpaper rotation runs on a systemd user timer.
# The unit files are written from templates under ~/.config/systemd/user/, but
# systemd does not see them on its own: daemon-reload + enable are needed.
# If this step is skipped the files sit there and NOTHING happens — the user is
# left with "I turned on rotation but it does not work".
#
# IMPORTANT — ORDERING: this is NOT a hook. install.sh runs the hooks BEFORE
# render_run; as a hook the unit files would not be written yet and
# "systemctl --user list-unit-files" could never see them. So it is called
# in install.sh main() AFTER render_run.
enable_wallpaper_rotation() {
    [[ "${WALLPAPER_ROTATE:-0}" =~ ^[0-9]+$ ]] || return 0
    (( WALLPAPER_ROTATE > 0 )) || return 0
    [[ "${SKIP_CONFIGS:-0}" == 1 ]] && return 0
    # The timer only makes sense with a supported wallpaper backend.
    in_list "swww" "${SELECTED[@]}" || in_list "hyprpaper" "${SELECTED[@]}" || return 0

    step "Wallpaper rotation: every $WALLPAPER_ROTATE minutes"
    run systemctl --user daemon-reload || true
    enable_user_service "hyprsetup-wallpaper.timer"
    # enable on its own only says "start at boot"; it is also started so it
    # runs in this session too.
    run systemctl --user start hyprsetup-wallpaper.timer \
        || warn "Could not start the timer — try logging in again."
}

hook_hyprpaper() { _ensure_wallpaper; }
hook_swww()      { _ensure_wallpaper; }

# waypaper is not a wallpaper daemon on its own but a picker UI — it hands the
# actual work to a "backend" like hyprpaper/swww. Since WALLPAPER_DAEMON is
# single-choice in our catalog, none of those packages is installed separately
# while waypaper is selected; the generated config.ini assumes the "hyprpaper"
# backend by default, so the user is warned if it is not installed.
hook_waypaper() {
    _ensure_wallpaper
    have hyprpaper || warn "waypaper's default backend is 'hyprpaper' but it is not installed — pick another backend in the waypaper UI."
}
